// Silinx - a System's CPU node's sketch kept as its drawings are (#5486, core/reactive-c-main.js): made again from the
// node's drawings' C whenever one of them is made or made again (core/drawing-sync.js) and before its firmware is
// compiled (server/avr-compile.js, so that a drawing deleted since is no longer called), removed when none is left. A
// hand-written .ino in the node's folder is its program instead: no sketch made (it calls the drawings' functions).
// A store P as core/drawing-sync.js's (the server's projects, the page's). Isomorphic ES module, no DOM.
import { isNodeMain, nodeMain, nodeMainPath } from './reactive-c-main.js';
import { REACTIVE_KINDS, drawingKind } from './reactive-from.js';
import { relInNode } from './system-layout.js';

/**
 * The node's sketch made again from its drawings: { path, written, removed, messages } (messages the console's lines:
 * made, updated, removed, the pins two drawings take), or null (none to make: not a C or C++ node, a hand-written sketch).
 */
export async function syncNodeMain(P, name, node, lang) {
  const tree = await P.fileTree(name);
  const path = nodeMainPath(node.id), mine = f => relInNode(f, node.id) != null && !/^build\//.test(relInNode(f, node.id));
  const read = f => P.readFile(name, f).catch(() => null);
  const now = tree.includes(path) ? await read(path) : null;
  // (a node no longer of C nor C++: its sketch made from its drawings removed)
  if (lang !== 'c' && lang !== 'cpp') {
    if (now == null || !isNodeMain(now)) return null;
    await P.deleteFile(name, path);
    return { path, written: null, removed: path, messages: [`${path} removed: ${node.id}'s language is not C`] };
  }
  // (a hand-written sketch of the node's: its program; an .ino generated from one drawing alone, before: not one)
  for (const f of tree.filter(f => mine(f) && /\.ino$/i.test(f))) if (!/generated by Silinx/.test(String(f === path ? now : await read(f)).split('\n', 1)[0])) return null;
  const units = [];
  for (const f of tree.filter(f => mine(f) && REACTIVE_KINDS.includes(drawingKind(f))).sort()) {
    let gf;
    try { gf = JSON.parse(await read(f))?.generatedFile; } catch { continue; }
    if (gf && /\.(c|cpp)$/i.test(gf) && tree.includes(gf)) units.push({ module: gf.split('/').pop().replace(/\.\w+$/, ''), file: f, code: await read(gf), cpp: /\.cpp$/i.test(gf) });
  }
  const main = nodeMain(node.id, units);
  if (!main) {
    if (now == null || !isNodeMain(now)) return null;
    await P.deleteFile(name, path);
    return { path, written: null, removed: path, messages: [`${path} removed: ${node.id} has no drawing with its C`] };
  }
  const warn = main.warnings.map(w => `WARNING: ${w}`);
  if (now === main.code) return { path, written: null, removed: null, messages: warn };
  await P.writeFile(name, path, main.code);
  return { path, written: path, removed: null, messages: [`${path} ${now == null ? 'generated' : 'updated'} from ${node.id}'s drawings`, ...warn] };
}
