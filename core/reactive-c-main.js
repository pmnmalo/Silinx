// Silinx - a System's CPU node's sketch, made from its drawings (#5486, docs/SYSTEMS.md): each drawing of the node is a
// unit of its program (core/reactive-c.js generateUnit: its own C or C++ file, its <module>_init() and <module>_tick()),
// and the node's one sketch, `<id>/<id>.ino`, calls them all: setup() each one's init, loop() each one's tick every
// TICK_MS milliseconds, in the order of their files. arduino-cli joins all of a folder's .ino into one, so one sketch a
// node: a hand-written .ino of the node's is its program instead, which calls its drawings' functions itself (none made).
// The drawings' pins are said when two of them take the same one.
// Isomorphic ES module: no DOM and no Node APIs.
import { TICK_MS } from './reactive-c.js';

/** The first line of a sketch Silinx made from its node's drawings (one that is not is hand-written). */
export const MAIN_MARK = 'generated by Silinx from the node\'s drawings';
/** Whether the text of an .ino is the sketch Silinx made from its node's drawings. */
export const isNodeMain = (text) => String(text ?? '').split('\n', 1)[0].includes(MAIN_MARK);
/** The node's sketch's path. */
export const nodeMainPath = (id) => `${id}/${id}.ino`;

// a unit's pins, from its header's lines (`// Inputs: a D2, k D3 D4.`): [pin, port, out]
const unitPins = (code) => String(code).split('\n').filter((l) => /^\/\/ (Inputs|Outputs): /.test(l))
  .flatMap((l) => l.replace(/^\/\/ \w+: /, '').replace(/\.$/, '').split(', ').flatMap((x) => { const [port, ...pins] = x.split(' '); return pins.map((p) => [p, port, l.startsWith('// Outputs')]); }));

/**
 * The node's sketch: { code, warnings } (warnings: a pin two drawings take, one of them writing it), or null (no unit). `id` the node's, `units`
 * [{ module, file (its drawing), code, cpp (its C a .cpp: else C, its functions declared extern "C", the .ino being
 * C++) }] in their files' order.
 */
export function nodeMain(id, units, { tickMs = TICK_MS } = {}) {
  if (!units.length) return null;
  // (a pin two drawings read: both read it; one that one of them writes: said)
  // (a pin two drawings read: both read it; one that one of them writes: said, the pins of the same two ports at once)
  const owners = new Map(), clashes = new Map();
  for (const u of units) {
    for (const [pin, port, out] of unitPins(u.code)) {
      const os = owners.get(pin) ?? [], o = os.find((x) => x.module !== u.module && (x.out || out));
      if (o) { const k = `${o.module}'s ${o.port} and ${u.module}'s ${port}`; clashes.set(k, [...(clashes.get(k) ?? []), pin]); }
      owners.set(pin, [...os, { module: u.module, port, out }]);
    }
  }
  const warnings = [...clashes].map(([k, pins]) => `${id}: ${pins.join(' ')} ${pins.length > 1 ? 'are' : 'is'} ${k}: give one of them its pins (a GPIO interface of the node named as its port)`);
  const decl = (u) => [`void ${u.module}_init(void);`, `void ${u.module}_tick(void);`];
  const c = units.filter((u) => !u.cpp), cpp = units.filter((u) => u.cpp);
  const L = [
    `// ${id}: its program, ${MAIN_MARK} (${units.map((u) => u.file.split('/').pop()).join(', ')}): edit the drawings, not this file.`,
    '// setup() calls each drawing\'s <module>_init(), loop() each one\'s <module>_tick() every TICK_MS milliseconds.',
    '', '#include <Arduino.h>', '', '// ---- the drawings\' functions (their files next to this one)',
    ...(c.length ? ['extern "C" {', ...c.flatMap(decl).map((l) => `  ${l}`), '}'] : []), ...cpp.flatMap(decl),
    '', `const unsigned long TICK_MS = ${tickMs};   // the tick's period`,
    '', 'void setup() {', ...units.map((u) => `  ${u.module}_init();`), '}',
    '', 'void loop() {', '  static unsigned long lastTick = 0;', '  if (millis() - lastTick < TICK_MS) return;', '  lastTick += TICK_MS;',
    ...units.map((u) => `  ${u.module}_tick();`), '}', '',
  ];
  return { code: L.join('\n'), warnings };
}
