// A register map's program side (#5288; the map: core/regmap.js): the C header an Arduino's program includes to read and
// write the FPGA's registers, through the Arduino core's SPI (SS on the board's SS pin, mode 0, MSB first) or Wire (the
// map's I²C address), as the FPGA's slave (core/regmap-hdl.js) has the protocol. Each register's address a #define, its
// read and write functions with its type (uint8_t, uint16_t, uint32_t); an ro register has no write, a wo no read.
// Isomorphic ES module, no DOM.
//
//   const { code, file } = regmapHeader(map);   // file: '<name>.h'

import { regsByAddr } from './regmap.js';

const hex2 = v => `0x${v.toString(16).padStart(2, '0')}`;
const cType = w => (w <= 8 ? 'uint8_t' : w <= 16 ? 'uint16_t' : 'uint32_t');

/** The map's header: { code, file: '<name>.h' }. */
export function regmapHeader(m) {
  const regs = regsByAddr(m), N = m.name.toUpperCase(), n = m.name, spi = m.bus === 'spi';
  const L = [`// ${n}.h: the registers of the register map ${n}.regs.json, the FPGA's, over ${spi ? 'SPI' : `I2C at the address ${hex2(m.address)}`}.`,
    '// Generated by Silinx (edit the map, not this file).',
    spi ? '// In setup(): SPI.begin(); (SS, D10 on an Uno, is an output then, high).' : '// In setup(): Wire.begin();',
    `#ifndef ${N}_H`, `#define ${N}_H`, '', '#include <Arduino.h>', spi ? '#include <SPI.h>' : '#include <Wire.h>', ''];
  if (spi) L.push(`#ifndef ${N}_SPI_HZ`, `#define ${N}_SPI_HZ 125000   // the SCK rate: the System's SPI interface's`, '#endif', '');
  else L.push(`#define ${N}_I2C_ADDRESS ${hex2(m.address)}`, '');
  const nw = Math.max(...regs.map(r => r.name.length), 1);
  for (const r of regs) L.push(`#define ${`${N}_${r.name.toUpperCase()}`.padEnd(N.length + 1 + nw)} ${hex2(r.addr)}   // ${r.width} bit(s), ${r.access}${r.strobe ? ', a pulse when written' : ''}`);
  L.push('', '// n bytes at addr, the least significant first');
  if (spi) {
    L.push(`static inline void ${n}_write(uint8_t addr, uint32_t v, uint8_t n) {`, `  SPI.beginTransaction(SPISettings(${N}_SPI_HZ, MSBFIRST, SPI_MODE0));`, '  digitalWrite(SS, LOW);',
      '  SPI.transfer(addr & 0x7f);', '  for (uint8_t i = 0; i < n; i++, v >>= 8) SPI.transfer(v & 0xff);', '  digitalWrite(SS, HIGH);', '  SPI.endTransaction();', '}',
      `static inline uint32_t ${n}_read(uint8_t addr, uint8_t n) {`, '  uint32_t v = 0;', `  SPI.beginTransaction(SPISettings(${N}_SPI_HZ, MSBFIRST, SPI_MODE0));`, '  digitalWrite(SS, LOW);',
      '  SPI.transfer(0x80 | addr);', '  for (uint8_t i = 0; i < n; i++) v |= (uint32_t)SPI.transfer(0) << (8 * i);', '  digitalWrite(SS, HIGH);', '  SPI.endTransaction();', '  return v;', '}');
  } else {
    L.push(`static inline void ${n}_write(uint8_t addr, uint32_t v, uint8_t n) {`, `  Wire.beginTransmission(${N}_I2C_ADDRESS);`, '  Wire.write(addr);',
      '  for (uint8_t i = 0; i < n; i++, v >>= 8) Wire.write((uint8_t)(v & 0xff));', '  Wire.endTransmission();', '}',
      `static inline uint32_t ${n}_read(uint8_t addr, uint8_t n) {`, '  uint32_t v = 0;', `  Wire.beginTransmission(${N}_I2C_ADDRESS);`, '  Wire.write(addr);', '  Wire.endTransmission(false);   // a repeated START',
      `  Wire.requestFrom((uint8_t)${N}_I2C_ADDRESS, n);`, '  for (uint8_t i = 0; i < n && Wire.available(); i++) v |= (uint32_t)Wire.read() << (8 * i);', '  return v;', '}');
  }
  L.push('');
  for (const r of regs) {
    const t = cType(r.width), A = `${N}_${r.name.toUpperCase()}`;
    if (r.access !== 'wo') L.push(`static inline ${t} ${n}_read_${r.name}(void) { return (${t})${n}_read(${A}, ${r.bytes}); }`);
    if (r.access !== 'ro') L.push(`static inline void ${n}_write_${r.name}(${t} v) { ${n}_write(${A}, v, ${r.bytes}); }`);
  }
  L.push('', `#endif  // ${N}_H`, '');
  return { code: L.join('\n'), file: `${n}.h` };
}
