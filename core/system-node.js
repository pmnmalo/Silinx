// Silinx - a System's FPGA node as a project of its own, to implement it on its own board (#5446, roadmap #4695's
// phase 3, docs/SYSTEMS.md): its module the top, its board and variant the device, its constraints made from its pins
// (port bit -> package pin) in the device's format, each pin with what its board's resource says of it (pull, drive,
// slew, a clock's period and its route), as Update Constraints writes a board's (core/board-constraints.js). The
// project's own description is not changed: the node's is derived, its build its own (server/system-implement.js:
// build/nodes/<id>/). Isomorphic module (browser + Node).
import { boardConstraintsText, bitName, constraintsExtOf, deviceLabel, periodNs } from '../packages/silinx-fpga/src/parts.js';
import { resolveBoard } from './devices.js';
import { withProfile } from './project-profile.js';
import { isName } from './ident.js';
import { nodeIdError } from './system-doc.js';
import { relInNode } from './system-layout.js';

const same = (a, b) => String(a ?? '').toUpperCase() === String(b ?? '').toUpperCase();

/** An FPGA node's board ({ …board, device, resources }: its variant's), or null when it names none known. */
export function nodeBoard(node) {
  const r = node?.board ? resolveBoard(node.board, { variant: node.variant }) : null;
  return r ? { ...r.board, device: r.device, resources: r.resources } : null;
}

/** Why the FPGA node `node` cannot be implemented, or null: not an FPGA node, no module, no board, no pin. */
export function nodeRefusal(node) {
  if (!isName(String(node?.id ?? ''))) return nodeIdError(node?.id ?? '');   // (its id names its build folder, #5446)
  if (node?.kind !== 'fpga') return `${node?.id ?? '?'}: only an FPGA node is implemented on a board`;
  if (!node.module) return `${node.id}: an FPGA node with no module`;
  if (!node.board) return `${node.id}: an FPGA node with no board`;
  if (!nodeBoard(node)) return `${node.id}: no FPGA board '${node.board}'${node.variant ? ` (variant ${node.variant})` : ''}`;
  if (!Object.keys(node.pins || {}).length) return `${node.id}: its module's ports are on no pin of its board (its I/O Pin Planning)`;
  return null;
}

/**
 * The constraints of the FPGA node `node` (its module's `ports`: core/board-constraints.js ucfPort's): { path (its
 * file's name, `<id>` and the device's format's extension), text }. Each of its pins with its board's resource's
 * attributes; a pin of a clock its period.
 */
export function nodeConstraints(node, ports) {
  const board = nodeBoard(node), d = board.device;
  const assignments = {}, clocks = [];
  const scalar = new Set(ports.filter(p => (p.width ?? 1) === 1 && (p.msb === null || p.msb === undefined)).map(p => bitName(p.name)));
  for (const [net, pin] of Object.entries(node.pins)) {
    const r = board.resources.find(x => x.pins.some(q => same(q, pin)));
    const a = { loc: String(pin).toUpperCase() };
    if (r?.pull) a.pull = r.pull;
    if (r?.drive) a.drive = r.drive;
    if (r?.slew) a.slew = r.slew;
    if (r?.clockDedicatedRoute === false) a.clockDedicatedRoute = false;
    Object.defineProperty(assignments, net, { value: a, enumerable: true, writable: true, configurable: true });
    if (r?.group === 'Clock' && scalar.has(net)) clocks.push({ net, period: periodNs(r.extra?.period || '20 ns'), duty: 50 });
  }
  const text = boardConstraintsText({ device: d, board, ports, assignments, clocks,
    header: `UCF for the System node '${node.id}' (top '${node.module}') on ${board.name} (${deviceLabel(d)}), generated by Silinx` });
  return { path: `${node.id}${constraintsExtOf(d)}`, text };
}

/** The project `pj` as the FPGA node `node` implements it: an FPGA project, its top the node's module, its board and
 *  device the node's, its constraints `constraints` (nodeConstraints's path), its files those of the node's folder
 *  (#5488); nothing else changed. */
export function nodeProject(pj, node, constraints) {
  const board = nodeBoard(node);
  const files = (pj.files || []).filter(f => relInNode(f.path, node.id) != null);
  return { ...withProfile(pj, 'fpga'), top: node.module, board: node.board, device: { ...board.device }, constraints, topSourceType: 'hdl', files };
}
