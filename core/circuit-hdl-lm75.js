// A temperature sensor LM75 (I²C) in a circuit's HDL (#5342, core/circuit-lm75.js and core/circuit-i2c.js the live
// simulation's): an entity of its own (<circuit>_lm75, its generics the part's id and its saved temperature in
// half-degrees), simulation only (behind `synthesis translate_off`: a sensor, no logic of the design), its I²C peripheral
// and its registers as the live ones: its address 0x48 + A2..A0 acknowledged (SDA pulled low, `sda` '0' or 'Z', read back
// on `sda_rd`), a write's pointer and its register's bytes, a read's bytes sent bit by bit as SCL falls and the master's
// ACK or NACK; its OS (open drain, `os`) in comparator or interrupt mode, its temperature converted at power-on and as
// its configuration is written (its temperature fixed: the HDL's). Each byte it sends it says: `U1 sends 25`. The same
// in VHDL and in Verilog, checked against the live one (test/circuit-lm75.test.js). Isomorphic module.

/** The entity's name in a circuit. */
export const lm75Entity = (circuit) => `${circuit}_lm75`;
// (its ports: gnd, vcc, scl, sda_rd, a0, a1, a2, sda, os: core/circuit-hdl.js's lm75Map)

/** Its VHDL (lines pushed to L). */
export function vhdlLm75(L, name) {
  L.push('-- a temperature sensor LM75 (I2C), its peripheral and its registers as Silinx simulates them: each byte it sends said',
    'library ieee;', 'use ieee.std_logic_1164.all;', '',
    `entity ${name} is`, '  generic ( id : string := "U"; temp : integer := 50 );',
    '  port ( gnd, vcc, scl, sda_rd, a0, a1, a2 : in std_logic; sda, os : out std_logic := \'Z\' );', `end entity ${name};`, '',
    `architecture model of ${name} is`, 'begin',
    '  -- silinx: ignore data-as-clock comb-loop (SCL and SDA read as the chip reads them; SDA driven and read back, open drain)',
    '  process (scl, sda_rd, vcc, gnd)',
    '    variable pscl, psda : std_logic := \'U\';',
    '    variable st : natural range 0 to 4 := 0;   -- (idle, its address, written, ignored, read)',
    '    variable bits, sent : natural range 0 to 8 := 0;',
    '    variable b, outb, conf, pointer, n : natural range 0 to 255 := 0;',
    '    variable acking, mack, pw, active, pull, tosnext : boolean := false;',
    '    variable rawt, thyst, tos : natural range 0 to 65535 := 0;',
    '    variable rd, over, under, q : natural range 0 to 255 := 0;',
    '    function bit_of(s : std_logic) return natural is begin if s = \'1\' then return 1; else return 0; end if; end function;',
    '    function halves(r : natural) return integer is begin if (r / 128) mod 512 >= 256 then return (r / 128) mod 512 - 512; else return (r / 128) mod 512; end if; end function;',
    '    function pw2(k : natural) return natural is variable r : natural := 1; begin for i in 1 to k loop r := r * 2; end loop; return r; end function;',
    '    function fq(c : natural) return natural is begin',
    '      case (c / 8) mod 4 is when 0 => return 1; when 1 => return 2; when 2 => return 4; when others => return 6; end case; end function;',
    '  begin',
    '    if not (vcc = \'1\' and gnd = \'0\') then',
    '      st := 0; bits := 0; b := 0; acking := false; conf := 0; pointer := 0; n := 0; rd := 0; sent := 0;',
    '      thyst := 75 * 256; tos := 80 * 256; active := false; over := 0; under := 0; tosnext := true; pull := false; pw := false; sda <= \'Z\'; os <= \'Z\';',
    '    else',
    '      if not pw then',
    '        pw := true; rawt := ((temp + 512) mod 512) * 128;',
    '        if halves(rawt) > halves(tos) then over := 1; end if;',
    '        if over >= 1 then active := true; tosnext := false; end if;',
    '      end if;',
    '      if scl = \'1\' and pscl = \'1\' and sda_rd /= psda then',
    '        if sda_rd = \'0\' and psda = \'1\' then st := 1; bits := 0; b := 0; acking := false; pull := false;',
    '        elsif sda_rd = \'1\' and psda = \'0\' then st := 0; acking := false; pull := false; end if;',
    '      elsif st = 4 then',
    '        if scl = \'1\' and pscl = \'0\' and sent = 8 then mack := sda_rd = \'0\'; end if;',
    '        if scl = \'0\' and pscl = \'1\' then',
    '          if acking or (sent = 8 and mack) then',
    '            acking := false;',
    '            if pointer = 1 then outb := conf; elsif rd mod 2 = 0 then',
    '              if pointer = 0 then outb := rawt / 256; elsif pointer = 2 then outb := thyst / 256; else outb := tos / 256; end if;',
    '            else',
    '              if pointer = 0 then outb := rawt mod 256; elsif pointer = 2 then outb := thyst mod 256; else outb := tos mod 256; end if;',
    '            end if;',
    '            rd := (rd + 1) mod 256; sent := 0; pull := (outb / 128) mod 2 = 0;',
    '            report id & " sends " & integer\'image(outb);',
    '          elsif sent < 7 then sent := sent + 1; pull := (outb / pw2(7 - sent)) mod 2 = 0;',
    '          elsif sent = 7 then sent := 8; pull := false; mack := false;',
    '          else st := 3; pull := false; end if;',
    '        end if;',
    '      elsif st = 1 or st = 2 then',
    '        if scl = \'1\' and pscl = \'0\' and not acking then',
    '          if sda_rd = \'1\' then b := (b * 2 + 1) mod 256; else b := (b * 2) mod 256; end if;',
    '          bits := bits + 1;',
    '        end if;',
    '        if scl = \'0\' and pscl = \'1\' then',
    '          if acking then acking := false; pull := false; bits := 0; b := 0;',
    '          elsif bits = 8 then',
    '            if st = 1 then',
    '              if b / 2 = 72 + bit_of(a2) * 4 + bit_of(a1) * 2 + bit_of(a0) then',
    '                acking := true; pull := true; n := 0; rd := 0;',
    '                if b mod 2 = 1 then st := 4; if (conf / 2) mod 2 = 1 then active := false; end if; else st := 2; end if;',
    '              else st := 3; bits := 0; end if;',
    '            else',
    '              acking := true; pull := true;',
    '              if n = 0 then pointer := b mod 4;',
    '              elsif pointer = 1 and n = 1 then',
    '                conf := b mod 32;',
    '                -- (a conversion: OS as its fault queue and its mode say)',
    '                if conf mod 2 = 0 then',
    '                  q := fq(conf);',
    '                  if halves(rawt) > halves(tos) then over := over + 1; else over := 0; end if;',
    '                  if halves(rawt) < halves(thyst) then under := under + 1; else under := 0; end if;',
    '                  if (conf / 2) mod 2 = 0 then if over >= q then active := true; elsif under >= q then active := false; end if;',
    '                  elsif tosnext and over >= q then active := true; tosnext := false;',
    '                  elsif not tosnext and under >= q and not active then active := true; tosnext := true; end if;',
    '                end if;',
    '              elsif pointer = 2 then if n = 1 then thyst := b * 256 + thyst mod 256; else thyst := (thyst / 256) * 256 + (b / 128) * 128; end if;',
    '              elsif pointer = 3 then if n = 1 then tos := b * 256 + tos mod 256; else tos := (tos / 256) * 256 + (b / 128) * 128; end if;',
    '              end if;',
    '              n := (n + 1) mod 256;',
    '            end if;',
    '          end if;',
    '        end if;',
    '      end if;',
    '      if pull then sda <= \'0\'; else sda <= \'Z\'; end if;',
    '      if active /= ((conf / 4) mod 2 = 1) then os <= \'0\'; else os <= \'Z\'; end if;',
    '    end if;',
    '    pscl := scl; psda := sda_rd;',
    '  end process;',
    'end architecture model;', '');
}

/** Its Verilog (lines pushed to L). */
export function verilogLm75(L, name) {
  L.push('// a temperature sensor LM75 (I2C), its peripheral and its registers as Silinx simulates them: each byte it sends said',
    `module ${name} #(parameter ID = "U", parameter integer TEMP = 50) (input gnd, vcc, scl, sda_rd, a0, a1, a2, output sda, output os);`,
    '  reg pscl, psda, acking, mack, pw, active, pull, tosnext;',
    '  integer st, bits, sent, b, outb, conf, pointer, n, rawt, thyst, tos, rd, over, under, q;',
    '  assign sda = pull ? 1\'b0 : 1\'bz;   // silinx: ignore comb-loop (open drain: SDA driven and read back)',
    '  assign os = (pw && (active != conf[2])) ? 1\'b0 : 1\'bz;',
    '  function integer halves(input integer r); halves = ((r >> 7) & 511) >= 256 ? ((r >> 7) & 511) - 512 : ((r >> 7) & 511); endfunction',
    '  function integer fq(input integer c); fq = ((c >> 3) & 3) == 0 ? 1 : ((c >> 3) & 3) == 1 ? 2 : ((c >> 3) & 3) == 2 ? 4 : 6; endfunction',
    '  task reset; begin st = 0; bits = 0; b = 0; acking = 0; conf = 0; pointer = 0; n = 0; rd = 0; sent = 0; thyst = 75 * 256; tos = 80 * 256;',
    '    active = 0; over = 0; under = 0; tosnext = 1; pull = 0; pw = 0; mack = 0; end endtask',
    '  initial begin reset; pscl = 1\'bx; psda = 1\'bx; end',
    '  // silinx: ignore data-as-clock clock-as-data comb-loop latch sensitivity (SCL and SDA read as the chip reads them; SDA driven and read back, open drain; its state held between the bus\'s edges)',
    '  always @(scl or sda_rd or vcc or gnd) begin',
    '    if (!(vcc === 1\'b1 && gnd === 1\'b0)) reset;',
    '    else begin',
    '      if (!pw) begin',
    '        pw = 1; rawt = ((TEMP + 512) % 512) * 128;',
    '        if (halves(rawt) > halves(tos)) over = 1;',
    '        if (over >= 1) begin active = 1; tosnext = 0; end',
    '      end',
    '      if (scl === 1\'b1 && pscl === 1\'b1 && sda_rd !== psda) begin',
    '        if (sda_rd === 1\'b0 && psda === 1\'b1) begin st = 1; bits = 0; b = 0; acking = 0; pull = 0; end',
    '        else if (sda_rd === 1\'b1 && psda === 1\'b0) begin st = 0; acking = 0; pull = 0; end',
    '      end else if (st == 4) begin',
    '        if (scl === 1\'b1 && pscl === 1\'b0 && sent == 8) mack = sda_rd === 1\'b0;',
    '        if (scl === 1\'b0 && pscl === 1\'b1) begin',
    '          if (acking || (sent == 8 && mack)) begin',
    '            acking = 0;',
    '            if (pointer == 1) outb = conf;',
    '            else if (rd % 2 == 0) outb = (pointer == 0 ? rawt : pointer == 2 ? thyst : tos) / 256;',
    '            else outb = (pointer == 0 ? rawt : pointer == 2 ? thyst : tos) % 256;',
    '            rd = (rd + 1) % 256; sent = 0; pull = ((outb >> 7) & 1) == 0;',
    '            $display("%0s sends %0d", ID, outb);',
    '          end else if (sent < 7) begin sent = sent + 1; pull = ((outb >> (7 - sent)) & 1) == 0; end',
    '          else if (sent == 7) begin sent = 8; pull = 0; mack = 0; end',
    '          else begin st = 3; pull = 0; end',
    '        end',
    '      end else if (st == 1 || st == 2) begin',
    '        if (scl === 1\'b1 && pscl === 1\'b0 && !acking) begin b = ((b << 1) | (sda_rd === 1\'b1)) & 255; bits = bits + 1; end',
    '        if (scl === 1\'b0 && pscl === 1\'b1) begin',
    '          if (acking) begin acking = 0; pull = 0; bits = 0; b = 0; end',
    '          else if (bits == 8) begin',
    '            if (st == 1) begin',
    '              if ((b >> 1) == 72 + (a2 === 1\'b1) * 4 + (a1 === 1\'b1) * 2 + (a0 === 1\'b1)) begin',
    '                acking = 1; pull = 1; n = 0; rd = 0;',
    '                if (b & 1) begin st = 4; if ((conf >> 1) & 1) active = 0; end else st = 2;',
    '              end else begin st = 3; bits = 0; end',
    '            end else begin',
    '              acking = 1; pull = 1;',
    '              if (n == 0) pointer = b % 4;',
    '              else if (pointer == 1 && n == 1) begin',
    '                conf = b % 32;',
    '                if (!(conf & 1)) begin',
    '                  q = fq(conf);',
    '                  over = halves(rawt) > halves(tos) ? over + 1 : 0;',
    '                  under = halves(rawt) < halves(thyst) ? under + 1 : 0;',
    '                  if (!((conf >> 1) & 1)) begin if (over >= q) active = 1; else if (under >= q) active = 0; end',
    '                  else if (tosnext && over >= q) begin active = 1; tosnext = 0; end',
    '                  else if (!tosnext && under >= q && !active) begin active = 1; tosnext = 1; end',
    '                end',
    '              end',
    '              else if (pointer == 2) thyst = n == 1 ? b * 256 + thyst % 256 : (thyst / 256) * 256 + (b / 128) * 128;',
    '              else if (pointer == 3) tos = n == 1 ? b * 256 + tos % 256 : (tos / 256) * 256 + (b / 128) * 128;',
    '              n = (n + 1) % 256;',
    '            end',
    '          end',
    '        end',
    '      end',
    '    end',
    '    pscl = scl; psda = sda_rd;',
    '  end',
    'endmodule', '');
  // (a model's state held between the bus's edges: latches, on purpose, its lines said so)
  const at = L.findIndex((l) => l.startsWith('  always @(scl'));
  for (let i = at + 1; i < L.length && L[i] !== 'endmodule'; i++) if (/[=(]/.test(L[i])) L[i] += '   // silinx: ignore latch';
}
