// A project's constraints file made from its board's pins (#4732), as Update Constraints writes it: the top's ports
// matched to the board's resources by name (clk, led, sw, btn, seg, an…), the others by direction (inputs on the
// switches and buttons, outputs on the LEDs). The interface (web/js/implement.js regenerateUcf) and the server
// (server/projects.js boardConstraints: the MCP's set_top and set_design_properties, a new project's) write the same
// file. Isomorphic module (browser + Node).

import { boardAutoAssign, boardConstraintsText, deviceLabel } from '../packages/silinx-fpga/src/parts.js';
import { resolveBoard } from './devices.js';

/** A top port as the constraints read it: { name, dir, width, msb, lsb } (msb / lsb: a bus's, else null). */
export function ucfPort(p) {
  const t = p.sig.t, bus = t.w > 1 || (t.kind === 'logic' && !t.scalar);
  return { name: p.name, dir: p.dir, width: t.w, msb: bus ? t.left : null, lsb: bus ? t.right : null };
}

/** A project's board ({ …board, device, resources }: its variant's device and resources) by its id and its device's
 *  part; null for none. */
export function boardOfProject(pj) {
  const r = pj?.board ? resolveBoard(pj.board, { part: pj.device?.part }) : null;
  return r ? { ...r.board, device: r.device, resources: r.resources } : null;
}

/**
 * The constraints file of top `top` (its name) with ports `ports` (ucfPort's) on `board` (boardOfProject's): { text,
 * matched, unmatched } (the ports given a pin, those given none).
 */
export function boardConstraintsFile(top, ports, board) {
  const { assignments, clocks, matched, unmatched } = boardAutoAssign(ports, board, { byDirection: true });
  const d = board.device;
  const text = boardConstraintsText({ device: d, board, ports, assignments, clocks, header: `UCF for top '${top}' on ${board.name} (${deviceLabel(d)}), generated by Silinx` });
  return { text, matched, unmatched };
}
