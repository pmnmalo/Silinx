// A graphic OLED 128×64 (SSD1306, I²C) in a circuit's HDL (#5336, core/circuit-oled.js and core/circuit-i2c.js the live
// simulation's): an entity of its own (<circuit>_ssd1306, its generic id the part's), simulation only (behind `synthesis
// translate_off`: a display, no logic of the design), its I²C peripheral and its controller as the live ones: its address
// 0x3C acknowledged (SDA pulled low, `sda` '0' or 'Z', read back on `sda_rd`), each byte after it, the control byte, the
// commands and their parameters, the addressing modes, the GDDRAM; reset while unpowered (VCC 1, GND 0). After a STOP
// that changes what it shows, it says it: `OLED1 on 8 0 0 0 0 0 0 0` (the bits set in each of its 8 pages) or `OLED1 off`
// (its display or its charge pump off). The same in VHDL and in Verilog, checked against the live one
// (test/circuit-oled.test.js). Isomorphic module.

// (its ports: the pins' (GND, VCC, SCL) and SDA's two sides: `sda` driven, '0' or 'Z', and `sda_rd` the net read)

/** The entity's name in a circuit. */
export const oledEntity = (circuit) => `${circuit}_ssd1306`;

// the commands' parameters (core/circuit-oled.js's PARAMS)
const PARAMS = { 0x20: 1, 0x21: 2, 0x22: 2, 0x81: 1, 0x8d: 1, 0xa8: 1, 0xd3: 1, 0xd5: 1, 0xd9: 1, 0xda: 1, 0xdb: 1, 0x26: 6, 0x27: 6, 0x29: 5, 0x2a: 5, 0xa3: 2 };
const paramsCase = (V) => Object.entries(PARAMS).map(([k, n]) => (V ? `when ${k} => need := ${n};` : `${k}: need = ${n};`));

/** Its VHDL (lines pushed to L). */
export function vhdlOled(L, name) {
  L.push('-- a graphic OLED 128x64 (SSD1306, I2C), its peripheral and its controller as Silinx simulates them: what it shows said after each STOP',
    'library ieee;', 'use ieee.std_logic_1164.all;', '',
    `entity ${name} is`, '  generic ( id : string := "OLED" );', '  port ( gnd, vcc, scl, sda_rd : in std_logic; sda : out std_logic := \'Z\' );', `end entity ${name};`, '',
    `architecture model of ${name} is`, 'begin',
    '  -- silinx: ignore data-as-clock comb-loop (SCL and SDA read as the module reads them; SDA driven and read back, open drain)',
    '  process (scl, sda_rd, vcc, gnd)',
    '    type ram_t is array (0 to 1023) of natural range 0 to 255;',
    '    type said_t is array (0 to 8) of natural range 0 to 1024;',
    '    variable ram : ram_t := (others => 0);',
    '    variable seen, said : said_t := (others => 0);',
    '    variable pscl, psda : std_logic := \'U\';',
    '    variable st : natural range 0 to 3 := 0;   -- (idle, its address, data, ignored)',
    '    variable bits : natural range 0 to 8 := 0;',
    '    variable b, v : natural range 0 to 255 := 0;',
    '    variable acking, ctl, co, dc, dispon, pump, pw, done : boolean := false;',
    '    variable op, need, got, a0 : natural range 0 to 255 := 0;',
    '    variable mode : natural range 0 to 3 := 2;',
    '    variable c0, col : natural range 0 to 127 := 0;',
    '    variable c1 : natural range 0 to 127 := 127;',
    '    variable p0, pg : natural range 0 to 7 := 0;',
    '    variable p1 : natural range 0 to 7 := 7;',
    '  begin',
    '    if not (vcc = \'1\' and gnd = \'0\') then',
    '      ram := (others => 0); st := 0; bits := 0; b := 0; acking := false; ctl := false; dispon := false; pump := false;',
    '      mode := 2; c0 := 0; c1 := 127; p0 := 0; p1 := 7; col := 0; pg := 0; need := 0; got := 0; sda <= \'Z\';',
    '      said := (others => 0); pw := false;',
    '    elsif pw then',
    '      done := false;',
    '      if scl = \'1\' and pscl = \'1\' and sda_rd /= psda then',
    '        if sda_rd = \'0\' and psda = \'1\' then',
    '          if st = 2 then done := true; end if;',
    '          st := 1; bits := 0; b := 0; acking := false; sda <= \'Z\';',
    '        elsif sda_rd = \'1\' and psda = \'0\' then',
    '          if st = 2 then done := true; end if;',
    '          st := 0; acking := false; sda <= \'Z\';',
    '        end if;',
    '      elsif st = 1 or st = 2 then',
    '        if scl = \'1\' and pscl = \'0\' and not acking then',
    '          if sda_rd = \'1\' then b := (b * 2 + 1) mod 256; else b := (b * 2) mod 256; end if;',
    '          bits := bits + 1;',
    '        end if;',
    '        if scl = \'0\' and pscl = \'1\' then',
    '          if acking then acking := false; sda <= \'Z\'; bits := 0; b := 0;',
    '          elsif bits = 8 then',
    `            if st = 1 then`,
    '              if b = 120 then st := 2; acking := true; sda <= \'0\'; ctl := false; else st := 3; bits := 0; end if;',
    '            else',
    '              acking := true; sda <= \'0\';',
    '              if not ctl then ctl := true; co := b >= 128; dc := (b / 64) mod 2 = 1;',
    '              else',
    '                if dc then',
    '                  ram(pg * 128 + col) := b;',
    '                  if mode = 0 then if col = c1 then col := c0; if pg = p1 then pg := p0; else pg := pg + 1; end if; else col := col + 1; end if;',
    '                  elsif mode = 1 then if pg = p1 then pg := p0; if col = c1 then col := c0; else col := col + 1; end if; else pg := pg + 1; end if;',
    '                  else col := (col + 1) mod 128; end if;',
    '                elsif need > 0 then',
    '                  got := got + 1;',
    '                  if got = 1 then a0 := b; end if;',
    '                  if got = need then',
    '                    need := 0;',
    '                    if op = 32 then mode := a0 mod 4;',
    '                    elsif op = 33 then c0 := a0 mod 128; c1 := b mod 128; col := c0;',
    '                    elsif op = 34 then p0 := a0 mod 8; p1 := b mod 8; pg := p0;',
    '                    elsif op = 141 then pump := (a0 / 4) mod 2 = 1; end if;',
    '                  end if;',
    '                else',
    '                  op := b; need := 0; got := 0;',
    '                  case b is', ...paramsCase(true).map((x) => `                    ${x}`), '                    when others => null;', '                  end case;',
    '                  if b = 174 then dispon := false; elsif b = 175 then dispon := true;',
    '                  elsif b >= 176 and b <= 183 then pg := b - 176;',
    '                  elsif b <= 15 then col := (col / 16) * 16 + b;',
    '                  elsif b <= 31 then col := (b - 16) mod 8 * 16 + col mod 16; end if;',
    '                end if;',
    '                if co then ctl := false; end if;',
    '              end if;',
    '            end if;',
    '          end if;',
    '        end if;',
    '      end if;',
    '      if done then',
    '        seen := (others => 0);',
    '        if dispon and pump then seen(8) := 1; end if;',
    '        for i in 0 to 1023 loop',
    '          v := ram(i);',
    '          for k in 0 to 7 loop seen(i / 128) := seen(i / 128) + v mod 2; v := v / 2; end loop;',
    '        end loop;',
    '        if seen /= said then',
    '          said := seen;',
    '          if seen(8) = 1 then report id & " on " & integer\'image(seen(0)) & " " & integer\'image(seen(1)) & " " & integer\'image(seen(2)) & " " & integer\'image(seen(3))',
    '            & " " & integer\'image(seen(4)) & " " & integer\'image(seen(5)) & " " & integer\'image(seen(6)) & " " & integer\'image(seen(7));',
    '          else report id & " off"; end if;',
    '        end if;',
    '      end if;',
    '    end if;',
    '    if vcc = \'1\' and gnd = \'0\' then pw := true; end if;',
    '    pscl := scl; psda := sda_rd;',
    '  end process;',
    'end architecture model;', '');
  // (its ACK held between the bus's edges: a latch of the model's, on purpose, its lines said so)
  for (let i = 0; i < L.length; i++) if (/sda <= '[0Z]';/.test(L[i]) && !L[i].includes('silinx:')) L[i] += '   -- silinx: ignore latch comb-loop';
}

/** Its Verilog (lines pushed to L). */
export function verilogOled(L, name) {
  L.push('// a graphic OLED 128x64 (SSD1306, I2C), its peripheral and its controller as Silinx simulates them: what it shows said after each STOP',
    `module ${name} #(parameter ID = "OLED") (input gnd, vcc, scl, sda_rd, output sda);`,
    '  reg [7:0] ram [0:1023];',
    '  integer seen [0:8];',
    '  integer said [0:8];',
    '  reg pscl, psda, pull, acking, ctl, co, dc, dispon, pump, pw, done, changed;',
    '  integer st, bits, b, v, op, need, got, a0, mode, c0, c1, col, p0, p1, pg, i, k;',
    '  assign sda = pull ? 1\'b0 : 1\'bz;   // silinx: ignore comb-loop (open drain: SDA driven and read back)',
    '  task reset; begin',
    '    for (i = 0; i < 1024; i = i + 1) ram[i] = 0;',
    '    for (i = 0; i < 9; i = i + 1) said[i] = 0;',
    '    st = 0; bits = 0; b = 0; acking = 0; ctl = 0; dispon = 0; pump = 0; mode = 2; c0 = 0; c1 = 127; p0 = 0; p1 = 7;',
    '    col = 0; pg = 0; need = 0; got = 0; pull = 0; pw = 0;',
    '  end endtask',
    '  initial begin reset; pscl = 1\'bx; psda = 1\'bx; end',
    '  // silinx: ignore data-as-clock clock-as-data comb-loop latch sensitivity (SCL and SDA read as the module reads them; SDA driven and read back, open drain; its state held between the bus\'s edges)',
    '  always @(scl or sda_rd or vcc or gnd) begin',
    '    if (!(vcc === 1\'b1 && gnd === 1\'b0)) reset;',
    '    else if (pw) begin',
    '      done = 0;',
    '      if (scl === 1\'b1 && pscl === 1\'b1 && sda_rd !== psda) begin',
    '        if (sda_rd === 1\'b0 && psda === 1\'b1) begin if (st == 2) done = 1; st = 1; bits = 0; b = 0; acking = 0; pull = 0; end',
    '        else if (sda_rd === 1\'b1 && psda === 1\'b0) begin if (st == 2) done = 1; st = 0; acking = 0; pull = 0; end',
    '      end',
    '      else if (st == 1 || st == 2) begin',
    '        if (scl === 1\'b1 && pscl === 1\'b0 && !acking) begin b = (b * 2 + (sda_rd === 1\'b1)) % 256; bits = bits + 1; end',
    '        if (scl === 1\'b0 && pscl === 1\'b1) begin',
    '          if (acking) begin acking = 0; pull = 0; bits = 0; b = 0; end',
    '          else if (bits == 8) begin',
    '            if (st == 1) begin',
    '              if (b == 120) begin st = 2; acking = 1; pull = 1; ctl = 0; end else begin st = 3; bits = 0; end',
    '            end else begin',
    '              acking = 1; pull = 1;',
    '              if (!ctl) begin ctl = 1; co = b >= 128; dc = (b / 64) % 2; end',
    '              else begin',
    '                if (dc) begin',
    '                  ram[pg * 128 + col] = b;',
    '                  if (mode == 0) begin if (col == c1) begin col = c0; pg = (pg == p1) ? p0 : pg + 1; end else col = col + 1; end',
    '                  else if (mode == 1) begin if (pg == p1) begin pg = p0; col = (col == c1) ? c0 : col + 1; end else pg = pg + 1; end',
    '                  else col = (col + 1) % 128;',
    '                end',
    '                else if (need > 0) begin',
    '                  got = got + 1;',
    '                  if (got == 1) a0 = b;',
    '                  if (got == need) begin',
    '                    need = 0;',
    '                    if (op == 32) mode = a0 % 4;',
    '                    else if (op == 33) begin c0 = a0 % 128; c1 = b % 128; col = c0; end',
    '                    else if (op == 34) begin p0 = a0 % 8; p1 = b % 8; pg = p0; end',
    '                    else if (op == 141) pump = (a0 / 4) % 2;',
    '                  end',
    '                end',
    '                else begin',
    '                  op = b; need = 0; got = 0;',
    '                  case (b)', ...paramsCase(false).map((x) => `                    ${x}`), '                    default: need = 0;', '                  endcase',
    '                  if (b == 174) dispon = 0; else if (b == 175) dispon = 1;',
    '                  else if (b >= 176 && b <= 183) pg = b - 176;',
    '                  else if (b <= 15) col = (col / 16) * 16 + b;',
    '                  else if (b <= 31) col = (b - 16) % 8 * 16 + col % 16;',
    '                end',
    '                if (co) ctl = 0;',
    '              end',
    '            end',
    '          end',
    '        end',
    '      end',
    '      if (done) begin',
    '        for (k = 0; k < 9; k = k + 1) seen[k] = 0;',
    '        if (dispon && pump) seen[8] = 1;',
    '        for (i = 0; i < 1024; i = i + 1) begin v = ram[i]; for (k = 0; k < 8; k = k + 1) begin seen[i / 128] = seen[i / 128] + v % 2; v = v / 2; end end',
    '        changed = 0;',
    '        for (k = 0; k < 9; k = k + 1) if (seen[k] != said[k]) changed = 1;',
    '        if (changed) begin',
    '          for (k = 0; k < 9; k = k + 1) said[k] = seen[k];',
    '          if (seen[8]) $display("%0s on %0d %0d %0d %0d %0d %0d %0d %0d", ID, seen[0], seen[1], seen[2], seen[3], seen[4], seen[5], seen[6], seen[7]);',
    '          else $display("%0s off", ID);',
    '        end',
    '      end',
    '    end',
    '    if (vcc === 1\'b1 && gnd === 1\'b0) pw = 1;',
    '    pscl = scl; psda = sda_rd;',
    '  end',
    'endmodule', '');
  // (a model's state held between the bus's edges: latches, on purpose, its lines said so)
  const at = L.findIndex((l) => l.startsWith('  always @(scl or sda_rd'));
  for (let i = at + 1; i < L.length && L[i] !== 'endmodule'; i++) if (/[=(]/.test(L[i])) L[i] += '   // silinx: ignore latch';
}
