// An SD card on SPI (a microSD module) in a circuit's HDL (#5477, core/circuit-sd.js the live simulation's): an entity of
// its own (<circuit>_sd, its generic id the part's), simulation only (behind `synthesis translate_off`: a card, no logic
// of the design), MISO driven while it is powered and CS is low (else Z): SPI mode 0 bit by bit on SCK's and CS's
// changes, the same commands as the live one (CMD0, CMD8, CMD55 + ACMD41, CMD58, CMD16, CMD13, CMD17, CMD24; CMD0's and
// CMD8's CRC7; its answers queued a byte after each command), what it does said as the live one logs it: `SD1 ready`,
// `SD1 wrote block 5`, `SD1 read block 5`; it keeps 4 blocks (a fifth written said, not kept). The same in VHDL and in
// Verilog, checked against the live one (test/circuit-sd.test.js). Isomorphic module.

/** The entity's name in a circuit. */
export const sdEntity = (circuit) => `${circuit}_sd`;

/** Its VHDL (lines pushed to L). */
export function vhdlSd(L, name) {
  L.push('-- an SD card on SPI (a microSD module), its answers as Silinx simulates them', 'library ieee;', 'use ieee.std_logic_1164.all;', 'use ieee.numeric_std.all;', '',
    `entity ${name} is`, '  generic ( id : string := "SD" );', '  port ( vcc, gnd, sck, mosi, cs : in std_logic; miso : out std_logic );', `end entity ${name};`, '',
    `architecture model of ${name} is`,
    '  type bytes is array (natural range <>) of integer range 0 to 255;',
    '  type tags_t is array (0 to 3) of integer range -1 to 65535;',
    'begin',
    '  process',
    '    variable q : bytes(0 to 1023);',
    '    variable mem : bytes(0 to 2047) := (others => 0);',
    '    variable tags : tags_t := (others => -1);',
    '    variable cmd : bytes(0 to 5);',
    '    variable qh, qt : integer range 0 to 1023 := 0;',
    '    variable stage, inits : integer range 0 to 2 := 0;',
    '    variable clocks : integer range 0 to 1000000 := 0;',
    '    variable nc : integer range 0 to 6 := 0;',
    '    variable bits : integer range 0 to 8 := 0;',
    '    variable rx, tx, nxt, b, r1 : integer range 0 to 255 := 255;',
    '    variable rxmode : integer range 0 to 2 := 0;',
    '    variable rxn : integer range 0 to 514 := 0;',
    '    variable blk : integer range 0 to 65535 := 0;',
    '    variable slot : integer range -1 to 3 := -1;',
    '    variable arg : integer range 0 to 2147483647;   -- (one past 2**31 - 1 saturated: no block that far)',
    '    variable idx : integer range 0 to 63;',
    '    variable app, up, sel : boolean := false;',
    '    variable psck : std_logic := \'0\';',
    '    variable c7 : std_logic_vector(6 downto 0);',
    '    variable c16 : std_logic_vector(15 downto 0);',
    '    variable v8 : std_logic_vector(7 downto 0);',
    '    variable f : std_logic;',
    '  begin',
    '    if not (vcc = \'1\' and gnd = \'0\') then',
    '      miso <= \'Z\';',
    '      if up then stage := 0; clocks := 0; nc := 0; qh := 0; qt := 0; app := false; inits := 0; rxmode := 0; end if;',
    '      up := false; sel := false; psck := \'0\'; nxt := 255;',
    '    else',
    '      up := true;',
    '      -- (CS: selected, its first bit set; released, MISO released)',
    '      if (cs = \'0\') /= sel then',
    '        sel := cs = \'0\';',
    '        if sel then bits := 0; tx := nxt; v8 := std_logic_vector(to_unsigned(tx, 8)); miso <= v8(7); else nc := 0; miso <= \'Z\'; end if;',
    '      end if;',
    '      if sck /= psck then',
    '        psck := sck;',
    '        if not sel then',
    '          if sck = \'1\' and stage = 0 and clocks < 1000000 then clocks := clocks + 1; end if;',
    '        elsif sck = \'1\' then',
    '          rx := (rx * 2) mod 256; if mosi = \'1\' then rx := rx + 1; end if;',
    '          bits := bits + 1;',
    '          if bits = 8 then',
    '            bits := 0; b := rx;',
    '            -- (the byte received: a block being written, a command\'s byte, or idle)',
    '            if rxmode = 1 then',
    '              if b = 254 then rxmode := 2; rxn := 0; end if;',
    '            elsif rxmode = 2 then',
    '              if rxn < 512 and slot >= 0 then mem(slot * 512 + rxn) := b; end if;',
    '              rxn := rxn + 1;',
    '              if rxn = 514 then',
    '                rxmode := 0;',
    '                if slot >= 0 then report id & " wrote block " & integer\'image(blk); end if;',
    '                q(qt) := 229; qt := qt + 1;',
    '                for i in 1 to 8 loop q(qt) := 0; qt := qt + 1; end loop;',
    '              end if;',
    '            elsif nc > 0 or (b >= 64 and b < 128) then',
    '              cmd(nc) := b; nc := nc + 1;',
    '              if nc = 6 then',
    '                nc := 0; idx := cmd(0) mod 64;',
    '                if cmd(1) >= 128 then arg := 2147483647; else arg := ((cmd(1) * 256 + cmd(2)) * 256 + cmd(3)) * 256 + cmd(4); end if;',
    '                c7 := (others => \'0\');',
    '                for i in 0 to 4 loop',
    '                  v8 := std_logic_vector(to_unsigned(cmd(i), 8));',
    '                  for k in 7 downto 0 loop f := v8(k) xor c7(6); c7 := c7(5 downto 0) & \'0\'; if f = \'1\' then c7 := c7 xor "0001001"; end if; end loop;',
    '                end loop;',
    '                if stage = 0 and clocks >= 74 then stage := 1; end if;',
    '                if stage > 0 then',
    '                  r1 := 0;',
    '                  if (idx = 0 or idx = 8) and cmd(5) /= to_integer(unsigned(c7)) * 2 + 1 then r1 := 8;',
    '                  elsif idx = 0 then stage := 1; inits := 0;',
    '                  elsif idx = 55 then null;',
    '                  elsif app and idx = 41 then if inits < 2 then inits := inits + 1; end if; if inits = 2 and stage = 1 then stage := 2; report id & " ready"; end if;',
    '                  elsif idx = 8 or idx = 58 or idx = 13 then null;',
    '                  elsif idx = 16 then if arg /= 512 then r1 := 64; end if;',
    '                  elsif idx = 17 or idx = 24 then if stage /= 2 then r1 := 4; elsif arg >= 65536 then r1 := 32; end if;',
    '                  else r1 := 4;',
    '                  end if;',
    '                  app := idx = 55 and r1 = 0;',
    '                  if stage = 1 then r1 := r1 + 1; end if;',
    '                  q(qt) := 255; qt := qt + 1; q(qt) := r1; qt := qt + 1;',
    '                  if r1 <= 1 then',
    '                    if idx = 8 then q(qt) := 0; q(qt + 1) := 0; q(qt + 2) := (arg / 256) mod 16; q(qt + 3) := arg mod 256; qt := qt + 4; end if;',
    '                    if idx = 13 then q(qt) := 0; qt := qt + 1; end if;',
    '                  end if;',
    '                  if r1 <= 1 and idx = 58 then if stage = 2 then q(qt) := 192; else q(qt) := 128; end if; q(qt + 1) := 255; q(qt + 2) := 128; q(qt + 3) := 0; qt := qt + 4; end if;',
    '                  if r1 = 0 and (idx = 17 or idx = 24) then',
    '                    blk := arg; slot := -1;',
    '                    for i in 0 to 3 loop if tags(i) = blk and slot < 0 then slot := i; end if; end loop;',
    '                    if idx = 24 then',
    '                      if slot < 0 then for i in 0 to 3 loop if tags(i) = -1 and slot < 0 then slot := i; tags(i) := blk; end if; end loop; end if;',
    '                      if slot < 0 then report id & ": a fifth block written: this HDL model keeps 4"; end if;',
    '                      rxmode := 1;',
    '                    else',
    '                      q(qt) := 255; q(qt + 1) := 254; qt := qt + 2; c16 := (others => \'0\');',
    '                      for i in 0 to 511 loop',
    '                        if slot >= 0 then b := mem(slot * 512 + i); else b := 0; end if;',
    '                        q(qt) := b; qt := qt + 1;',
    '                        c16 := c16 xor (std_logic_vector(to_unsigned(b, 8)) & x"00");',
    '                        for k in 0 to 7 loop if c16(15) = \'1\' then c16 := (c16(14 downto 0) & \'0\') xor x"1021"; else c16 := c16(14 downto 0) & \'0\'; end if; end loop;',
    '                      end loop;',
    '                      q(qt) := to_integer(unsigned(c16(15 downto 8))); q(qt + 1) := to_integer(unsigned(c16(7 downto 0))); qt := qt + 2;',
    '                      report id & " read block " & integer\'image(blk);',
    '                    end if;',
    '                  end if;',
    '                end if;',
    '              end if;',
    '            end if;',
    '            -- (the next byte sent: the queue\'s head, else idle)',
    '            if qh < qt then nxt := q(qh); qh := qh + 1; if qh = qt then qh := 0; qt := 0; end if; else nxt := 255; end if;',
    '          end if;',
    '        else',
    '          if bits = 0 then tx := nxt; end if;',
    '          v8 := std_logic_vector(to_unsigned(tx, 8)); miso <= v8(7 - bits);',
    '        end if;',
    '      end if;',
    '    end if;',
    '    wait on vcc, gnd, sck, cs;',
    '  end process;',
    'end architecture model;', '');
}

/** Its Verilog (lines pushed to L). */
export function verilogSd(L, name) {
  L.push('// an SD card on SPI (a microSD module), its answers as Silinx simulates them',
    `module ${name} #(parameter ID = "SD") (input vcc, gnd, sck, mosi, cs, output reg miso);`,
    '  reg [7:0] q [0:1023];',
    '  reg [7:0] mem [0:2047];',
    '  reg [7:0] cmd [0:5];',
    '  integer tags [0:3];',
    '  integer qh, qt, stage, inits, clocks, nc, bits, rxmode, rxn, blk, slot, arg, idx, i, k;',
    '  reg [7:0] rx, tx, nxt, b, r1;',
    '  reg [6:0] c7;',
    '  reg [15:0] c16;',
    '  reg app, up, sel, psck, f;',
    '  initial begin',
    '    miso = 1\'bz; qh = 0; qt = 0; stage = 0; inits = 0; clocks = 0; nc = 0; bits = 0; rxmode = 0; rxn = 0; blk = 0; slot = -1;',
    '    rx = 8\'hff; tx = 8\'hff; nxt = 8\'hff; app = 1\'b0; up = 1\'b0; sel = 1\'b0; psck = 1\'b0;',
    '    for (i = 0; i < 2048; i = i + 1) mem[i] = 8\'h00;',
    '    for (i = 0; i < 4; i = i + 1) tags[i] = -1;',
    '    forever begin',
    '      if (!(vcc === 1\'b1 && gnd === 1\'b0)) begin',
    '        miso = 1\'bz;',
    '        if (up) begin stage = 0; clocks = 0; nc = 0; qh = 0; qt = 0; app = 1\'b0; inits = 0; rxmode = 0; end',
    '        up = 1\'b0; sel = 1\'b0; psck = 1\'b0; nxt = 8\'hff;',
    '      end else begin',
    '        up = 1\'b1;',
    '        // (CS: selected, its first bit set; released, MISO released)',
    '        if ((cs === 1\'b0) != sel) begin',
    '          sel = cs === 1\'b0;',
    '          if (sel) begin bits = 0; tx = nxt; miso = tx[7]; end else begin nc = 0; miso = 1\'bz; end',
    '        end',
    '        if ((sck === 1\'b1) != psck) begin',
    '          psck = sck === 1\'b1;',
    '          if (!sel) begin',
    '            if (psck && stage == 0 && clocks < 1000000) clocks = clocks + 1;',
    '          end else if (psck) begin',
    '            rx = {rx[6:0], mosi === 1\'b1};',
    '            bits = bits + 1;',
    '            if (bits == 8) begin',
    '              bits = 0; b = rx;',
    '              // (the byte received: a block being written, a command\'s byte, or idle)',
    '              if (rxmode == 1) begin',
    '                if (b == 8\'hfe) begin rxmode = 2; rxn = 0; end',
    '              end else if (rxmode == 2) begin',
    '                if (rxn < 512 && slot >= 0) mem[slot * 512 + rxn] = b;',
    '                rxn = rxn + 1;',
    '                if (rxn == 514) begin',
    '                  rxmode = 0;',
    '                  if (slot >= 0) $display("%0s wrote block %0d", ID, blk);',
    '                  q[qt] = 8\'he5; qt = qt + 1;',
    '                  for (i = 0; i < 8; i = i + 1) begin q[qt] = 8\'h00; qt = qt + 1; end',
    '                end',
    '              end else if (nc > 0 || b[7:6] == 2\'b01) begin',
    '                cmd[nc] = b; nc = nc + 1;',
    '                if (nc == 6) begin',
    '                  nc = 0; idx = cmd[0] % 64; arg = {cmd[1], cmd[2], cmd[3], cmd[4]};',
    '                  c7 = 7\'d0;',
    '                  for (i = 0; i < 5; i = i + 1) for (k = 7; k >= 0; k = k - 1) begin f = cmd[i][k] ^ c7[6]; c7 = {c7[5:0], 1\'b0}; if (f) c7 = c7 ^ 7\'b0001001; end',
    '                  if (stage == 0 && clocks >= 74) stage = 1;',
    '                  if (stage > 0) begin',
    '                    r1 = 8\'h00;',
    '                    if ((idx == 0 || idx == 8) && cmd[5] != {c7, 1\'b1}) r1 = 8\'h08;',
    '                    else if (idx == 0) begin stage = 1; inits = 0; end',
    '                    else if (idx == 55) ;',
    '                    else if (app && idx == 41) begin if (inits < 2) inits = inits + 1; if (inits == 2 && stage == 1) begin stage = 2; $display("%0s ready", ID); end end',
    '                    else if (idx == 8 || idx == 58 || idx == 13) ;',
    '                    else if (idx == 16) begin if (arg != 512) r1 = 8\'h40; end',
    '                    else if (idx == 17 || idx == 24) begin if (stage != 2) r1 = 8\'h04; else if (arg >= 65536) r1 = 8\'h20; end',
    '                    else r1 = 8\'h04;',
    '                    app = idx == 55 && r1 == 0;',
    '                    if (stage == 1) r1 = r1 + 1;',
    '                    q[qt] = 8\'hff; q[qt + 1] = r1; qt = qt + 2;',
    '                    if (r1 <= 1) begin',
    '                      if (idx == 8) begin q[qt] = 0; q[qt + 1] = 0; q[qt + 2] = (arg >> 8) % 16; q[qt + 3] = arg % 256; qt = qt + 4; end',
    '                      if (idx == 13) begin q[qt] = 0; qt = qt + 1; end',
    '                      if (idx == 58) begin q[qt] = stage == 2 ? 8\'hc0 : 8\'h80; q[qt + 1] = 8\'hff; q[qt + 2] = 8\'h80; q[qt + 3] = 8\'h00; qt = qt + 4; end',
    '                    end',
    '                    if (r1 == 0 && (idx == 17 || idx == 24)) begin',
    '                      blk = arg; slot = -1;',
    '                      for (i = 0; i < 4; i = i + 1) if (tags[i] == blk && slot < 0) slot = i;',
    '                      if (idx == 24) begin',
    '                        if (slot < 0) for (i = 0; i < 4; i = i + 1) if (tags[i] == -1 && slot < 0) begin slot = i; tags[i] = blk; end',
    '                        if (slot < 0) $display("%0s: a fifth block written: this HDL model keeps 4", ID);',
    '                        rxmode = 1;',
    '                      end else begin',
    '                        q[qt] = 8\'hff; q[qt + 1] = 8\'hfe; qt = qt + 2; c16 = 16\'h0000;',
    '                        for (i = 0; i < 512; i = i + 1) begin',
    '                          b = slot >= 0 ? mem[slot * 512 + i] : 8\'h00;',
    '                          q[qt] = b; qt = qt + 1;',
    '                          c16 = c16 ^ {b, 8\'h00};',
    '                          for (k = 0; k < 8; k = k + 1) c16 = c16[15] ? {c16[14:0], 1\'b0} ^ 16\'h1021 : {c16[14:0], 1\'b0};',
    '                        end',
    '                        q[qt] = c16[15:8]; q[qt + 1] = c16[7:0]; qt = qt + 2;',
    '                        $display("%0s read block %0d", ID, blk);',
    '                      end',
    '                    end',
    '                  end',
    '                end',
    '              end',
    '              // (the next byte sent: the queue\'s head, else idle)',
    '              if (qh < qt) begin nxt = q[qh]; qh = qh + 1; if (qh == qt) begin qh = 0; qt = 0; end end else nxt = 8\'hff;',
    '            end',
    '          end else begin',
    '            if (bits == 0) tx = nxt;',
    '            miso = tx[7 - bits];',
    '          end',
    '        end',
    '      end',
    '      @(vcc or gnd or sck or cs);',
    '    end',
    '  end',
    'endmodule', '');
}
