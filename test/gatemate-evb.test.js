// Cologne Chip's GateMate FPGA Evaluation Board (#2431): its pins (LiteX's colognechip_gatemate_evb.py, after Cologne Chip's
// DS1003) in the board data, a project's constraints made from them as a CCF, placed and routed by nextpnr-himbaechel-gatemate;
// the CCGM1A1 and CCGM1A2 in the device database (Cologne Chip's DS1001, nextpnr's counts)
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { FAMILIES, findPart, findBoard, resolveBoard, validateDevice, partsOfFamily } from '../server/devices.js';
import { boardConstraints } from '../server/projects.js';
import { boardAutoAssign, boardConstraintsText, resourcesOf, GATEMATE_PARTS, CCF, runFlow, nextpnrGatemateNode, yosysNode } from '../packages/silinx-fpga/src/node.js';
import { constraintsDiagnostics } from '../core/constraints-check.js';

const io = (bank, ...ns) => ns.map(n => `IO_${bank}_${n}`);
// the board's own (LiteX's: clk10, user_led_n, user_btn_n), the headers of the banks NA and SA, the Pmods PMODA and PMODB
const OWN = { clk: ['IO_SB_A8'], led_n: io('EB', 'B1', 'B2', 'B3', 'B4', 'B5', 'B6', 'B7', 'B8'), btn_n: ['IO_EB_B0'] };
const BREADBOARD = { led: io('NA', 'A0', 'A1', 'A2', 'A3', 'A4', 'A5', 'A6', 'A7'), sw: io('SA', 'A0', 'A1', 'A2', 'A3', 'A4', 'A5', 'A6', 'A7'), btn: io('SA', 'B0', 'B1', 'B2', 'B3'),
  rx: ['IO_SA_B4'], tx: ['IO_SA_B5'] };
const PMODA = io('NB', 'A0', 'A1', 'A2', 'A3', 'B0', 'B1', 'B2', 'B3'), PMODB = io('NB', 'A4', 'A5', 'A6', 'A7');

test('the GateMate evaluation board in the board data: its own pins, the breadboard\'s on its headers, the display and the VGA on its Pmods', () => {
  const b = findBoard('gatemate-evb');
  assert.deepEqual(b.device, { family: 'gatemate', part: 'ccgm1a1', package: 'fbga324', speed: '' });
  assert.deepEqual(validateDevice(b.device), []);
  assert.equal(b.sourceUrl, 'https://github.com/litex-hub/litex-boards/blob/master/litex_boards/platforms/colognechip_gatemate_evb.py');
  const pins = Object.fromEntries(b.resources.map(r => [r.name, r.pins]));
  assert.deepEqual(pins, { ...OWN, ...BREADBOARD, seg: PMODA.slice(0, 7), dp: [PMODA[7]], an: PMODB });
  assert.equal(new Set(Object.values(pins).flat()).size, Object.values(pins).flat().length);
  for (const n of ['led_n', 'btn_n', 'seg', 'dp', 'an']) assert.equal(b.resources.find(r => r.name === n).extra.activeLow, true, n);
  assert.equal(b.resources.find(r => r.name === 'clk').extra.period, '100 ns');
  // (no I/O standard: a CCF has none, its bank's voltage)
  assert.deepEqual(b.resources.filter(r => r.iostandard), []);
  const v = findBoard('gatemate-evb-vga');
  assert.deepEqual(v.device, b.device);
  assert.deepEqual(Object.fromEntries(v.resources.map(r => [r.name, r.pins])),
    { ...OWN, ...BREADBOARD, vga_red: PMODA.slice(0, 3), vga_green: [PMODA[3], PMODA[4], PMODA[5]], vga_blue: PMODA.slice(6, 8), vga_hsync: [PMODB[0]], vga_vsync: [PMODB[1]] });
  for (const r of [...b.resources, ...v.resources]) assert.equal(r.verified, Object.keys(OWN).includes(r.name), r.name);
  // (no programming from Silinx: openFPGALoader's board, outside it)
  assert.equal(b.programmer.tools.openFPGALoader.board, 'gatemate_evb_jtag');
});

test('the GateMate in the device database: after the Gowin, the CCGM1A1 and CCGM1A2 of nextpnr\'s chip databases, their figures', () => {
  assert.deepEqual(FAMILIES.slice(-4).map(f => f.id), ['ice40', 'ecp5', 'gowin', 'gatemate']);
  assert.deepEqual(partsOfFamily('gatemate').map(p => p.part), Object.keys(GATEMATE_PARTS));
  const a1 = findPart('ccgm1a1'), a2 = findPart('ccgm1a2');
  assert.deepEqual([a1.logicCells, a1.luts, a1.ffs, a1.brams, a1.bramSize, a1.plls, a1.packages.fbga324.userIo, a1.speeds], [20480, 40960, 40960, 32, 40, 4, 162, []]);
  assert.deepEqual([a2.logicCells, a2.luts, a2.ffs, a2.brams, a2.plls, a2.packages.fbga324.userIo], [40960, 81920, 81920, 64, 8, 162]);
  const res = Object.fromEntries(resourcesOf(a1, 'fbga324').map(r => [r.id, r.count]));
  assert.deepEqual([res.luts, res.ffs, res.iob], [40960, 40960, 162]);
  assert.deepEqual(validateDevice({ part: 'ccgm1a1', package: 'fbga324', speed: '' }), []);
  assert.deepEqual(validateDevice({ part: 'ccgm1a1', package: 'cs132', speed: '' }), ["ccgm1a1 is not available in package 'cs132' (valid: fbga324)"]);
});

const TOP = 'module top(input clk, input btn_n, input [3:0] sw, output [7:0] led_n);\n  reg [23:0] c = 0;\n  always @(posedge clk) c <= c + 1;\n  assign led_n = ~{c[23:20], sw & {4{btn_n}}};\nendmodule\n';
const PORTS = [{ name: 'clk', dir: 'in', width: 1 }, { name: 'btn_n', dir: 'in', width: 1 }, { name: 'sw', dir: 'in', width: 4, msb: 3, lsb: 0 },
  { name: 'led_n', dir: 'out', width: 8, msb: 7, lsb: 0 }];
const CCF_TEXT = `# CCF for top 'top' on Cologne Chip GateMate FPGA Evaluation Board (ccgm1a1-fbga324), generated by Silinx\n\nNET "clk" Loc = "IO_SB_A8";\nNET "btn_n" Loc = "IO_EB_B0";\n`
  + `${BREADBOARD.sw.slice(0, 4).map((p, i) => `NET "sw[${i}]" Loc = "${p}";\n`).join('')}${OWN.led_n.map((p, i) => `NET "led_n[${i}]" Loc = "${p}";\n`).join('')}`
  + '# create_clock -period 100.000 [get_ports {clk}]\n';

test('a board\'s constraints in its family\'s format: a CCF on the evaluation board, read back the same, checked with no diagnostics', () => {
  const r = resolveBoard('gatemate-evb');
  const { assignments, clocks, unmatched } = boardAutoAssign(PORTS, { name: r.board.name, device: r.device, resources: r.resources });
  assert.deepEqual(unmatched, []);
  const text = boardConstraintsText({ device: r.device, board: { ...r.board, resources: r.resources }, ports: PORTS, assignments, clocks, header: "UCF for top 'top' on Cologne Chip GateMate FPGA Evaluation Board (ccgm1a1-fbga324), generated by Silinx" });
  assert.equal(text, CCF_TEXT);
  assert.deepEqual(CCF.read(text).clocks, [{ net: 'clk', period: 100 }]);
  assert.deepEqual(constraintsDiagnostics('ccf', text, { ports: PORTS, top: 'top', device: r.device, board: { ...r.board, resources: r.resources } }), []);
  // (a pin on no resource of the board, one given twice, a pin that is no GPIO, a port the top has not)
  assert.deepEqual(constraintsDiagnostics('ccf', 'NET "clk" Loc = "IO_WC_A0";\nNET "btn_n" Loc = "IO_WC_A0";\nNET "sw[0]" Loc = "Q9";\nNET "nope" Loc = "IO_EB_B0";\n',
    { ports: PORTS.slice(0, 2), device: r.device, board: { ...r.board, resources: r.resources } }), [
    { severity: 'warning', line: 1, message: 'NET clk: the pin IO_WC_A0 is on no resource of the Cologne Chip GateMate FPGA Evaluation Board' },
    { severity: 'error', line: 2, message: 'NET btn_n: the pin IO_WC_A0 is given to clk too (line 1)' },
    { severity: 'warning', line: 2, message: 'NET btn_n: the pin IO_WC_A0 is on no resource of the Cologne Chip GateMate FPGA Evaluation Board' },
    { severity: 'error', line: 3, message: 'NET sw[0]: Q9 is not a GPIO of the fbga324 package (its GPIOs look like IO_SB_A8, IO_EB_B1)' },
    { severity: 'warning', line: 3, message: 'NET sw[0]: the top has no such port' },
    { severity: 'warning', line: 4, message: 'NET nope: the top has no such port' },
  ]);
});

test('a project on the evaluation board: its constraints/top.ccf from the board, placed and routed at those pins, no warning', { timeout: 300000 }, async () => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'silinx-gatemate-evb-'));
  try {
    await fs.mkdir(path.join(dir, 'src'));
    await fs.writeFile(path.join(dir, 'src/top.v'), TOP);
    const pj = { name: 'gm', board: 'gatemate-evb', device: findBoard('gatemate-evb').device, top: 'top', files: [{ path: 'src/top.v', lang: 'verilog', role: 'design' }], constraints: 'constraints/top.ccf' };
    await boardConstraints(dir, pj);
    const ccf = await fs.readFile(path.join(dir, 'constraints/top.ccf'), 'utf8');
    assert.equal(ccf, CCF_TEXT);
    const log = [], files = {};
    const io = { log: l => log.push(l), sources: () => [{ path: 'top.v', lang: 'verilog', text: TOP }], ucf: ccf, ucfName: 'top.ccf',
      yosys: yosysNode, nextpnr: { gatemate: nextpnrGatemateNode() }, write: (n, d) => { files[n] = d; return `build/${n}`; }, read: n => files[n] ?? null, save: () => {} };
    const r = await runFlow({ top: 'top', family: 'gatemate', device: 'ccgm1a1', pkg: 'fbga324', speed: '', steps: ['synth', 'translate', 'par', 'bitgen'] }, io);
    assert.ok(r.ok, r.error);
    assert.deepEqual(log.filter(l => /^WARNING/.test(l)), []);
    assert.ok(r.report.par.constraintsMet);
    assert.deepEqual(r.report.par.fmax.map(f => [f.clock, f.constraint]), [['clk', 10]]);
    assert.ok(log.includes('Netlist of <top> read; constraints: top.ccf, 14 pin location(s), 1 PERIOD constraint(s).'));
    // (each port at its pin: nextpnr's configuration names the GPIOs it uses)
    assert.ok(files['top.bit'].length > 1000);
  } finally {
    await fs.rm(dir, { recursive: true, force: true });
  }
});
