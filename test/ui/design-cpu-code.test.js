// UI (#5486): a drawing in a System's CPU node on the Design pane (web/js/design-cpu.js): its row named after its module,
// its drawing's badge first (FSM, Open), its node's language's last ([C]: its generated C, `<module>.ino` next to it,
// opened from it); its C made when the project is opened (as the MCP's adoption: no HDL file, nothing added to the
// FPGA's design's sources); a drawing with errors: its [C] marked, not made, its tip why. Portuguese. No warnings. Both
// interfaces.
import { before, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { setupUi, uiTest, makeProject } from './harness.js';

let env;
before(async () => { env = await setupUi(); });
after(async () => { await env?.teardown?.(); });
const E = () => env;
const LOCK = (() => { const d = JSON.parse(fs.readFileSync(new URL('../../examples/lock/src/lock.fsm.json', import.meta.url), 'utf8')); delete d.generatedFile; return d; })();
const BROKEN = { ...LOCK, name: 'broken', transitions: LOCK.transitions.map((t, i) => (i ? t : { ...t, cond: `${t.cond} &&` })) };
const badges = (page, label) => page.eval((l) => [...[...document.querySelectorAll('#hier .row')].find((r) => r.querySelector('.lbl')?.textContent.trim() === l).querySelectorAll('.badge')].map((b) => [b.textContent, b.title, b.classList.contains('warn')]), label);
const lines = (page) => page.eval(() => [...document.querySelectorAll('#console-log .ln')].map((l) => l.textContent));
const file = (p) => env.server.api('GET', `/api/projects/Cpu/file?path=${encodeURIComponent(p)}`, undefined, { text: true }).then((t) => t, () => null);

uiTest('#5486 a CPU node\'s drawing: its row, [FSM] then [C] (its generated C, opened from it), made on opening; with errors marked; Portuguese', E, async (page) => {
  await makeProject(env, { name: 'Cpu', template: 'uart-avr', files: { 'uno/lock.fsm.json': JSON.stringify(LOCK, null, 2), 'uno/broken.fsm.json': JSON.stringify(BROKEN, null, 2) } });
  await page.openProject('Cpu');
  await page.leftTab('design');
  await page.waitConsole(/^uno\/lock\.ino generated from uno\/lock\.fsm\.json$/m);
  await page.waitFor(() => [...document.querySelectorAll('#hier .row .lbl')].some((l) => l.textContent.trim() === 'lock'), [], { what: 'the drawing\'s row' });
  // (its C made, linked; no HDL, nothing in the design's sources)
  assert.match(await file('uno/lock.ino'), /^\/\/ lock: a (Moore|Mealy) machine, generated by Silinx from the state diagram lock\.fsm\.json/);
  assert.equal(JSON.parse(await file('uno/lock.fsm.json')).generatedFile, 'uno/lock.ino');
  assert.deepEqual([await file('uno/lock.vhd'), await file('uno/lock.v'), await file('uno/broken.ino')], [null, null, null]);
  const pj = await env.server.api('GET', '/api/projects/Cpu');
  assert.deepEqual(pj.files.map((f) => f.path).filter((p) => p.startsWith('uno/')), []);
  // (the rows: the drawings first, the C no row of its own)
  const uno = await page.eval(() => [...[...document.querySelectorAll('#hier li')].find((li) => li.querySelector(':scope > .row .lbl')?.textContent.trim() === 'uno').querySelectorAll(':scope > ul > li > .row .lbl')].map((l) => l.textContent.trim()));
  assert.deepEqual(uno, ['broken', 'lock', 'hello.hex', 'hello.asm']);
  assert.deepEqual(await badges(page, 'lock'), [['FSM', 'Open', false], ['C', 'Generated from the state diagram', false]]);
  const [b0, b1] = await badges(page, 'broken');
  assert.deepEqual([b0, b1[0], b1[2]], [['FSM', 'Open', false], 'C', true]);
  assert.match(b1[1], /^Not made: it has errors: Transition .+: /);
  // ([C] opens its C)
  const at = await page.eval(() => { const r = [...document.querySelectorAll('#hier .row')].find((x) => x.querySelector('.lbl')?.textContent.trim() === 'lock'); const b = [...r.querySelectorAll('.badge')].find((x) => x.textContent === 'C'); b.scrollIntoView({ block: 'nearest' }); const k = b.getBoundingClientRect(); return { x: k.left + k.width / 2, y: k.top + k.height / 2 }; });
  await page.click(at);
  await page.waitFor(() => window.Silinx.active?.path === 'uno/lock.ino', [], { what: 'lock.ino open' });
  // (Portuguese)
  await page.eval(async () => { (await import('/js/i18n.js')).setLanguage('pt'); });
  await page.waitFor(() => [...document.querySelectorAll('#hier .badge')].some((b) => b.title === 'Gerado a partir do diagrama de estados'), [], { what: 'the badge in Portuguese' });
  assert.ok(await page.eval(() => [...document.querySelectorAll('#hier .badge')].some((b) => /^Não gerado: tem erros: Transition /.test(b.title))), 'the marked badge in Portuguese');
  await page.eval(async () => { (await import('/js/i18n.js')).setLanguage('en'); });
  assert.deepEqual((await lines(page)).filter((l) => /^(WARNING|ERROR)/.test(l)), []);
  assert.deepEqual(page.console.filter((c) => c.type === 'error' || c.type === 'warning' || c.type === 'warn').map((c) => c.text), []);
});
