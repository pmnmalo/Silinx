// UI: the Intel (Altera) boards (#5376): Terasic's DE boards in Design Properties, marked experimental, their families too;
// choosing the DE0-CV writes its pins as constraints/top.qsf and says no flow runs it yet; the process tree has no
// implementation (the constraints and the checks, Emulate); the QSF Wizard writes the board's pins with their I/O standards;
// I/O Pin Planning reads the QSF, its I/O standards Quartus's; Check Constraints of the QSF, its warnings exact; in Portuguese.
// Both interfaces.
import { before, after } from 'node:test';
import assert from 'node:assert/strict';
import { setupUi, uiTest, makeProject, readWs } from './harness.js';
import { TEXTS, untranslated } from './i18n-check.js';
import { newSourceWizardOf } from './new-source-helpers.js';

let env;
before(async () => { env = await setupUi(); });
after(async () => { await env?.teardown?.(); });
const E = () => env;

const TOP = 'module top(input clk, input [1:0] sw, output reg [1:0] led);\n  always @(posedge clk) led <= sw;\nendmodule\n';
const BASYS2 = { family: 'spartan3e', part: 'xc3s250e', package: 'cp132', speed: '-4' };
const DE1SOC = { family: 'cyclone5', part: '5csema5', package: 'f31', speed: 'c6' };
const NO_FLOW = 'WARNING: the 5CEBA4 (Cyclone V, an experimental family) has no implementation flow yet: its boards and its QSF constraints only (the Silinx toolchain\'s flow and Quartus Prime come next).';
const BOARDS = ['Terasic DE10-Lite (experimental)', 'Terasic DE0-CV (experimental)', 'Terasic DE1-SoC (experimental)', 'Terasic DE10-Nano (experimental)', 'Terasic DE0-Nano (experimental)', 'Terasic DE2-115 (experimental)'];

// the Design Properties dialog's lists
const fields = page => page.eval(() => {
  const sel = l => [...document.querySelectorAll('.dlg-overlay label')].find(x => x.textContent === l)?.nextElementSibling;
  const opts = s => [...s.options].map(o => o.textContent);
  return { boards: opts(sel('Evaluation Development Board:') || sel('Placa de Desenvolvimento:')), families: opts(sel('Family:') || sel('Família:')) };
});
const procLabels = page => page.eval(() => [...document.querySelectorAll('#procs .row')].map(x => x.textContent.trim().replace(/^▾/, '')));

uiTest('#5376 Design Properties: the DE boards, experimental; the DE0-CV\'s pins as a QSF, no implementation flow, Check Constraints of the QSF', E, async (page) => {
  await makeProject(env, { name: 'IntelPick', board: 'basys2', device: BASYS2, files: { 'src/top.v': TOP }, top: 'top' });
  await page.openProject('IntelPick');
  await page.menu('Project', 'Design Properties…');
  await page.waitDialog('Design Properties');
  const f = await fields(page);
  for (const b of BOARDS) assert.ok(f.boards.includes(b), `${b}: ${f.boards}`);
  for (const fam of ['MAX 10 (experimental)', 'Cyclone IV E (experimental)', 'Cyclone V (experimental)']) assert.ok(f.families.includes(fam), `${fam}: ${f.families}`);
  const chosen = await page.eval(() => {
    const sel = l => [...document.querySelectorAll('.dlg-overlay label')].find(x => x.textContent === l).nextElementSibling;
    const b = sel('Evaluation Development Board:'); b.value = 'de0-cv'; b.dispatchEvent(new Event('change'));
    return { part: sel('Device:').value, pkg: sel('Package:').value, speed: sel('Speed:').value, synth: sel('Synthesis Tool:').value, synthOff: sel('Synthesis Tool:').disabled };
  });
  assert.deepEqual(chosen, { part: '5ceba4', pkg: 'f23', speed: 'c7', synth: 'silinx', synthOff: true });
  await page.dialogButton('OK');
  await page.waitDialog('Update Constraints');
  await page.dialogButton('Yes');
  await page.waitNoDialog();
  await page.waitFor(() => window.Silinx.project.constraints === 'constraints/top.qsf', [], { what: 'the QSF the project\'s' });
  await page.waitConsole(/top\.qsf regenerated for Terasic DE0-CV/);
  const lines = (await page.consoleText()).split('\n').filter(l => /WARNING|ERROR|Device set|regenerated/.test(l));
  assert.deepEqual(lines, ['Device set to 5CEBA4F23C7 (board de0-cv).', NO_FLOW, 'constraints/top.qsf regenerated for Terasic DE0-CV: clk, sw, led']);
  const qsf = await readWs(env, 'IntelPick', 'constraints/top.qsf');
  assert.match(qsf, /^# QSF for top 'top' on Terasic DE0-CV \(5CEBA4F23C7\), generated by Silinx\n\nset_location_assignment PIN_M9 -to clk\nset_instance_assignment -name IO_STANDARD "3\.3-V LVTTL" -to clk\n/);
  assert.match(qsf, /\nset_location_assignment PIN_AA1 -to led\[1\]\nset_instance_assignment -name IO_STANDARD "3\.3-V LVTTL" -to led\[1\]\n\n# Timing constraints \(Quartus reads them from the SDC Silinx writes\)\n# create_clock -name \{clk\} -period 20\.000 \[get_ports \{clk\}\]\n$/);

  // the processes: no implementation yet: the constraints, the checks, Emulate (the HDL on the board's pins)
  await page.setView('impl');
  await page.treeRow('#hier', 'top');
  const labels = await procLabels(page);
  for (const present of ['I/O Pin Planning', 'View RTL Schematic', 'Check Syntax', 'Emulate on Board']) assert.ok(labels.includes(present), `${present}: ${labels}`);
  for (const absent of ['Synthesize - Yosys', 'Synthesize - XST', 'Implement Design', 'Generate Programming File', 'Configure Target Device']) assert.ok(!labels.some(l => l.startsWith(absent)), `${absent}: ${labels}`);
  // Implement asked anyway (the toolbar's step, a lab's task): refused with the message
  await page.eval(async () => (await import('/js/implement.js')).runImpl('top', ['synth']));
  await page.waitConsole(/has no implementation flow yet: its boards and its QSF constraints only/);

  // Check Constraints of the QSF: the project's clean; a port the top has not and a pin of no resource, their warnings; a line Quartus stops at
  const ports = [{ name: 'clk', width: 1 }, { name: 'sw', width: 2, msb: 1, lsb: 0 }, { name: 'led', width: 2, msb: 1, lsb: 0 }];
  const r = await page.eval(async (p) => {
    const { qsfDiagnostics, readPins, writePins, constraintsExt } = await import('/js/constraints-format.js');
    const device = { part: '5ceba4', package: 'f23', speed: 'c7' }, board = window.SilinxApp.projectBoard(window.Silinx.project);
    const read = readPins(device, 'set_location_assignment PIN_M9 -to clk\nset_instance_assignment -name IO_STANDARD "3.3-V LVTTL" -to clk\nset_location_assignment PIN_AA2 -to led[0]\n# create_clock -period 20 [get_ports clk]\n');
    return {
      ext: [constraintsExt(device), constraintsExt({ part: 'ep4ce22' }), constraintsExt({ part: '10m50da' }), constraintsExt({ part: 'xc3s250e' })],
      read: read.assignments,
      written: writePins(device, { assignments: read.assignments, clocks: read.clocks, header: 'H' }),
      good: qsfDiagnostics(await (await import('/js/api.js')).api.readFile('IntelPick', 'constraints/top.qsf'), p, { top: 'top', device, board }),
      unknown: qsfDiagnostics('set_location_assignment PIN_M9 -to clk\nset_location_assignment PIN_U7 -to key[0]\nset_location_assignment PIN_A1 -to sw[0]\n', p, { device, board }),
      bad: qsfDiagnostics('set_location_assignment PIN_M9 -to clk\nset_instance_assignment -name WEAK_PULL_UP_RESISTOR maybe -to clk\n', p, { device, board }),
    };
  }, ports);
  assert.deepEqual(r.ext, ['.qsf', '.qsf', '.qsf', '.ucf']);
  assert.deepEqual(r.read, { clk: { loc: 'PIN_M9', iostandard: '3.3-V LVTTL' }, 'led<0>': { loc: 'PIN_AA2' } });
  assert.equal(r.written, '# H\nset_location_assignment PIN_M9 -to clk\nset_instance_assignment -name IO_STANDARD "3.3-V LVTTL" -to clk\nset_location_assignment PIN_AA2 -to led[0]\n\n# Timing constraints (Quartus reads them from the SDC Silinx writes)\n# create_clock -name {clk} -period 20.000 [get_ports {clk}]\n');
  assert.deepEqual(r.good, []);
  assert.deepEqual(r.unknown, [{ severity: 'warning', line: 2, message: 'set_location_assignment key[0]: the top has no such port' },
    { severity: 'warning', line: 3, message: 'set_location_assignment sw[0]: the pin PIN_A1 is on no resource of the Terasic DE0-CV' }]);
  assert.deepEqual(r.bad, [{ severity: 'error', line: 2, message: 'WEAK_PULL_UP_RESISTOR maybe: ON or OFF' }]);
  await page.eval(async () => (await import('/js/implement.js')).checkUcfFile());
  await page.waitConsole(/Process "Check Constraints" completed successfully/);
  assert.deepEqual((await page.consoleText()).split('\n').filter(l => /ConstraintSystem/.test(l)), []);
});

uiTest('#5376 QSF Wizard on the DE1-SoC: the board\'s pins, their I/O standards from the board; I/O Pin Planning reads the QSF', E, async (page) => {
  await makeProject(env, { name: 'IntelWiz', board: 'de1-soc', device: DE1SOC, top: 'top', constraints: 'constraints/top.qsf', files: { 'src/top.v': TOP } });
  await page.openProject('IntelWiz');
  await newSourceWizardOf(page, 'Implementation Constraints File', 'pins', 'QSF Wizard');
  // (no attribute columns: a QSF's I/O standards the board's, I/O Pin Planning's to change)
  assert.deepEqual(await page.eval(() => [...document.querySelectorAll('.dlg-overlay .uw-pins th')].map(x => x.textContent)), ['Signal', 'Direction', 'Pin']);
  await page.dialogButton('Next >');
  await page.waitFor(() => document.querySelector('.dlg-overlay .wiz-main h3')?.textContent === 'Summary', [], { what: 'the Summary' });
  const preview = await page.eval(() => document.querySelector('.dlg-overlay .uw-preview').textContent);
  assert.equal(preview.split('\n')[0], "# QSF generated by the Silinx QSF Wizard for 'top' (5CSEMA5F31C6, Terasic DE1-SoC)");
  assert.match(preview, /\nset_location_assignment PIN_AF14 -to clk\nset_instance_assignment -name IO_STANDARD "3\.3-V LVTTL" -to clk\n/);
  assert.match(preview, /\nset_location_assignment PIN_AB12 -to sw\[0\]\n[\s\S]*\nset_location_assignment PIN_V16 -to led\[0\]\n/);
  await page.dialogButton('Finish');
  await page.waitNoDialog();
  await page.waitFor(() => window.Silinx.project.constraints === 'constraints/pins.qsf', [], { what: 'the project\'s constraints file' });
  assert.equal(await readWs(env, 'IntelWiz', 'constraints/pins.qsf'), preview);
  // I/O Pin Planning: the pins read back, the I/O standards offered the Cyclone V's (Quartus's names), a pull-up its only pull
  await page.eval(() => window.SilinxApp.openPinPlanner());
  await page.waitFor(() => document.querySelectorAll('.pp-table tr').length > 1, [], { what: 'I/O Pin Planning' });
  const pp = await page.eval(() => {
    const rows = [...document.querySelectorAll('.pp-table tr')].slice(1);
    const sel = (r, i) => r.cells[i].querySelector('select');
    return { rows: rows.map(r => `${r.cells[0].textContent} ${sel(r, 4).value} ${sel(r, 7).value}`), stds: [...sel(rows[0], 4).options].map(o => o.value).slice(0, 4),
      pulls: [...sel(rows[0], 7).options].map(o => o.value), drive: sel(rows[0], 5).disabled, slew: sel(rows[0], 6).disabled };
  });
  assert.deepEqual(pp.rows, ['clk 3.3-V LVTTL ', 'sw<0> 3.3-V LVTTL ', 'sw<1> 3.3-V LVTTL ', 'led<0> 3.3-V LVTTL ', 'led<1> 3.3-V LVTTL ']);
  assert.deepEqual(pp.stds, ['', '3.3-V LVTTL', '3.3-V LVCMOS', '3.0-V LVTTL']);
  assert.deepEqual([pp.pulls, pp.drive, pp.slew], [['', 'up'], true, true]);
});

uiTest('#5376 in Portuguese: the DE boards and the Intel families marked experimental, the QSF Wizard\'s title and labels translated', E, async (page) => {
  await makeProject(env, { name: 'IntelPt', board: 'de10-lite', device: { family: 'max10', part: '10m50da', package: 'f484', speed: 'c7g' }, top: 'top', constraints: 'constraints/top.qsf', files: { 'src/top.v': TOP } });
  await page.eval(async () => (await import('/js/i18n.js')).setLanguage('pt'));
  try {
    await page.openProject('IntelPt');
    await page.menu('Projeto', 'Propriedades do Projeto…');
    await page.waitDialog('Propriedades do Projeto');
    const f = await fields(page);
    const r = await page.eval(() => {
      const sel = l => [...document.querySelectorAll('.dlg-overlay label')].find(x => x.textContent === l)?.nextElementSibling;
      return { board: sel('Placa de Desenvolvimento:')?.selectedOptions[0]?.textContent, family: sel('Família:')?.selectedOptions[0]?.textContent, synthOff: sel('Ferramenta de Síntese:')?.disabled };
    });
    assert.deepEqual([r.board, r.family, r.synthOff], ['Terasic DE10-Lite (experimental)', 'MAX 10 (experimental)', true]);
    for (const b of BOARDS) assert.ok(f.boards.includes(b), `${b}: ${f.boards}`);
    await page.dialogButton('Cancelar');
  } finally { await page.eval(async () => (await import('/js/i18n.js')).setLanguage('en')); }
  // the QSF Wizard's pages in both languages: every label translated
  await newSourceWizardOf(page, 'Implementation Constraints File', 'pins', 'QSF Wizard');
  await page.eval(TEXTS);
  const setLang = l => page.eval(async x => { (await import('/js/i18n.js')).setLanguage(x); }, l);
  const missing = [];
  const compare = async where => {
    await setLang('en'); const en = await page.eval(() => window.__uiTexts(document.querySelector('.dlg-overlay')));
    await setLang('pt'); const pt = await page.eval(() => window.__uiTexts(document.querySelector('.dlg-overlay')));
    for (const s of untranslated(en, pt, [/^(clk|in|out)$/, /^\(none\)$/, /·/])) missing.push(`${where}: ${s}`);
    await setLang('en');
  };
  await compare('Ports and Pins');
  await setLang('pt');
  try { await page.waitDialog('Assistente de QSF'); } finally { await setLang('en'); }
  await page.dialogButton('Next >');
  await page.waitFor(() => document.querySelector('.dlg-overlay .wiz-main h3')?.textContent === 'Summary', [], { what: 'the Summary' });
  await compare('Summary');
  assert.deepEqual(missing, []);
  await page.dialogButton('Cancel');
});
