// The MCP server on the GateMate (#2431, #2674: what the interface does): list_devices lists the family, its CCGM1A1 and
// CCGM1A2 and Cologne Chip's evaluation board, set_design_properties makes the constraints a CCF from the board's pins,
// new_source writes the CCF template, check_constraints checks it, run_process builds its .bit (gmpack) and get_report gives
// its reports, its Post-Synthesis model simulates blinky's test bench; program_board refuses it (openFPGALoader's, outside
// Silinx); every result's text.
import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { scratchEnv } from './server-helpers.js';

let tmp;
before(async () => { tmp = await scratchEnv('silinx-mcp-gatemate-'); });
after(() => fs.rmSync(tmp, { recursive: true, force: true }));

const { handle } = await import('../server/mcp.js');
const P = await import('../server/projects.js');
let id = 0;
async function call(name, args = {}) {
  const r = (await handle({ jsonrpc: '2.0', id: ++id, method: 'tools/call', params: { name, arguments: args } })).result;
  return { text: r.content[0].text, data: r.structuredContent, isError: r.isError };
}
const ok = async (name, args) => { const r = await call(name, args); assert.equal(r.isError, false, r.text); return r; };
const fails = async (name, args, message) => { const r = await call(name, args); assert.equal(r.isError, true); assert.equal(r.text, `${name}: ${message}`); };

test('list_devices: the GateMate, its CCGM1A1 and CCGM1A2, the evaluation board and its VGA board', async () => {
  const all = await ok('list_devices');
  assert.deepEqual(all.data.boards.filter(b => /^gatemate/.test(b.id)).map(b => [b.id, b.device, b.experimental]),
    [['gatemate-evb', 'ccgm1a1fbga324', undefined], ['gatemate-evb-vga', 'ccgm1a1fbga324', undefined]]);
  const gm = await ok('list_devices', { family: 'gatemate' });
  assert.equal(gm.text, 'Devices:\n  GateMate (gatemate):\n    ccgm1a1: fbga324\n    ccgm1a2: fbga324');
});

test('set_design_properties: the evaluation board, its pins written as a CCF; new_source the CCF template; check_constraints', async () => {
  await ok('new_project_from_example', { name: 'b1', example: 'blinky' });
  const r = await ok('set_design_properties', { project: 'b1', board: 'gatemate-evb', update_constraints: true });
  assert.equal(r.text, 'WARNING: this device\'s constraints are CCF: constraints/top.ccf is the project\'s now, constraints/top.ucf was not converted.\n'
    // (its 10 MHz clock as the top's CLK_HZ, #3710)
    + 'src/top.vhd: CLK_HZ = 10_000_000, the Cologne Chip GateMate FPGA Evaluation Board\'s clock and inputs (the defaults of its generics).\n'
    + 'Device set to ccgm1a1-fbga324 (board gatemate-evb); synthesis tool silinx; constraints/top.ccf written from the gatemate-evb\'s pins.');
  const ccf = fs.readFileSync(path.join(P.projectDir('b1'), 'constraints/top.ccf'), 'utf8');
  assert.match(ccf, /^# CCF for top 'top' on Cologne Chip GateMate FPGA Evaluation Board \(ccgm1a1-fbga324\), generated by Silinx\n\nNET "clk" Loc = "IO_SB_A8";\n/);
  assert.match(ccf, /\n# create_clock -period 100\.000 \[get_ports \{clk\}\]\n$/);
  await fails('set_design_properties', { project: 'b1', synth_tool: 'xst' }, 'the CCGM1A1 is the Silinx toolchain\'s only: no XST');
  assert.equal((await ok('check_constraints', { project: 'b1' })).text, 'Started : "Check Constraints" of constraints/top.ccf.\nProcess "Check Constraints" completed successfully');
  assert.equal((await ok('new_source', { project: 'b1', type: 'constraints', name: 'pins' })).text, 'Created Implementation Constraints File \'constraints/pins.ccf\'.');
  assert.match(fs.readFileSync(path.join(P.projectDir('b1'), 'constraints/pins.ccf'), 'utf8'), /^# Cologne Chip constraints \(CCF\) for b1\n# Target: ccgm1a1-fbga324\n/);
  await fails('constraints_wizard', { project: 'b1' }, 'constraints/top.ccf already exists: choose another name.');
  await fails('clock_manager', { project: 'b1' }, 'The Clocking Wizard makes a DCM for the Spartan-3E and a PLL for the Spartan-6: choose one of them as the target device (set_design_properties).');
});

test('check_constraints: a CCF\'s errors, its pins and its DRIVE', async () => {
  await ok('new_project_from_example', { name: 'c1', example: 'gates' });
  await ok('set_design_properties', { project: 'c1', board: 'gatemate-evb', update_constraints: true });
  const F = 'constraints/gates.ccf', E = (line, m) => `ERROR:ConstraintSystem - "${F}" Line ${line}: ${m}`, W = (line, m) => `WARNING:ConstraintSystem - "${F}" Line ${line}: ${m}`;
  await ok('write_file', { project: 'c1', path: F, text: 'NET "led[0]" Loc = "B2" | DRIVE=5;\nPin_out "led[1]" Loc = "IO_NA_A1";\nLOCATE "x";\n' });
  assert.equal((await ok('check_constraints', { project: 'c1' })).text, ['Started : "Check Constraints" of constraints/gates.ccf.',
    E(3, 'LOCATE: not a CCF statement nextpnr-himbaechel-gatemate applies (NET, Pin_in, Pin_out, Pin_inout)'), 'Process "Check Constraints" failed (1 error(s), 0 warning(s))'].join('\n'));
  await ok('write_file', { project: 'c1', path: F, text: 'NET "led[0]" Loc = "B2" | DRIVE=5;\nPin_out "led[1]" Loc = "IO_NA_A1" | SLEW=medium;\nNET "sw[0]" Loc = "IO_SA_A0";\n' });
  assert.equal((await ok('check_constraints', { project: 'c1' })).text, ['Started : "Check Constraints" of constraints/gates.ccf.',
    E(1, 'NET led[0]: B2 is not a GPIO of the fbga324 package (its GPIOs look like IO_SB_A8, IO_EB_B1)'), E(1, 'DRIVE=5 of led[0]: 3, 6, 9 or 12 mA'),
    E(2, 'SLEW=medium of led[1]: SLOW or FAST'), W(3, "3 port bit(s) of 'gates' have no pin (NET): sw[1], sw[2], sw[3]"),
    'Process "Check Constraints" failed (3 error(s), 1 warning(s))'].join('\n'));
});

test('run_process: blinky on the evaluation board to its .bit, no warnings; get_report its reports; program_board refuses it', { timeout: 600000 }, async () => {
  await ok('new_project_from_example', { name: 'bi', example: 'blinky' });
  await ok('set_design_properties', { project: 'bi', board: 'gatemate-evb', update_constraints: true });
  const run = await ok('run_process', { project: 'bi', process: 'bitstream' });
  assert.deepEqual(run.data.warnings, []);
  assert.ok(fs.existsSync(path.join(P.projectDir('bi'), 'build', 'open', 'routed.cfg')));
  const summary = (await ok('get_report', { project: 'bi' })).data.summary;
  assert.deepEqual(summary.par.fmax.map(f => [f.clock, f.constraint]), [['clk', 10]]);
  assert.equal(summary.par.constraintsMet, true);
  assert.deepEqual(summary.map.utilization.map(u => u.name), ['CPE_FF', 'CPE_LT', 'GLBOUT', 'GPIO']);
  assert.ok(summary.bit.size > 1000);
  assert.ok(fs.existsSync(path.join(P.projectDir('bi'), 'build', 'top.bit')));
  // (no power estimate, no simulation model yet)
  await fails('run_process', { project: 'bi', process: 'power' }, 'no step xpwr (the steps: synth, postsynth, translate, par, trce, bitgen)');
  await P.updateProject('bi', pj => ({ ...pj, trusted: true }));
  await fails('program_board', { project: 'bi' }, 'a GateMate\'s board is not programmed from Silinx: its top.bit is loaded by openFPGALoader (openFPGALoader -b gatemate_evb_jtag top.bit), outside Silinx');
});

// the GateMate's Post-Synthesis model (core/flow-models-nextpnr.js: Yosys's netlist of the CC_ cells, gatemate-prims.js),
// simulated against blinky's test bench; no Post-Place & Route one
test('run_process post_synthesis_model on the evaluation board: blinky\'s model, its test bench passes on it, no warning; post_par_model refused', { timeout: 900000 }, async () => {
  await ok('new_project_from_example', { name: 'models', example: 'blinky' });
  await ok('set_design_properties', { project: 'models', board: 'gatemate-evb', update_constraints: true });
  const syn = await ok('run_process', { project: 'models', process: 'post_synthesis_model' });
  assert.deepEqual([syn.data.warnings, syn.data.errors], [[], []]);
  assert.match(syn.text, /^Post-Synthesis Simulation Model: build\/netgen\/synthesis\/top_synthesis\.v \(Verilog, the GateMate cells\), \d+ cells$/m);
  const s = await ok('simulate', { project: 'models', model: 'postsynth', time_ns: 2000000, signals: [] });
  assert.deepEqual([s.data.log.map(l => l.text).slice(-1), s.data.warnings, s.data.failed], [['Simulation finished OK'], [], false]);
  const message = 'the GateMate flow makes no post-place & route simulation model (only the post-synthesis one): simulate the behavioral model or the post-synthesis one';
  await fails('run_process', { project: 'models', process: 'post_par_model' }, message);
  await fails('simulate', { project: 'models', model: 'postpar', time_ns: 100 }, message);
});
