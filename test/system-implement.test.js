// A System's FPGA node implemented on its own board (#5446, core/system-node.js, server/system-implement.js): its
// constraints made from its pins (the uart-avr example's FPGA node: the uart example's UCF on the Basys2, line for line);
// the refusals; the node built by the Silinx toolchain in build/nodes/<id>/ (its bitstream the uart example's, the same
// module on the same board and pins), the project's build/ and silinx.json not touched; Implement System.
import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { scratchEnv, waitJob, ROOT } from './server-helpers.js';
import { nodeConstraints, nodeProject, nodeRefusal, nodeBoard } from '../core/system-node.js';
import { readSystem, writeSystem } from '../core/system-doc.js';
import { checkSystem } from '../core/system-check.js';
import { compile, elaborate } from '../core/compile.js';
import { ucfPort } from '../core/board-constraints.js';
import { setBuildChannel } from '../core/build-channel.js';

let tmp;
before(async () => { tmp = await scratchEnv('silinx-system-implement-'); setBuildChannel('dev'); });
after(() => fs.rmSync(tmp, { recursive: true, force: true }));
const P = await import('../server/projects.js');
const jobs = await import('../server/jobs.js');
const { startNodeImplementation } = await import('../server/system-implement.js');
const { startImplementation } = await import('../server/impl-routes.js');

const EX = path.join(ROOT, 'examples/uart-avr');
const NODE = readSystem(fs.readFileSync(path.join(EX, 'uart_avr.sys.json'), 'utf8')).system.nodes.find(n => n.kind === 'fpga');
const PORTS = (() => {
  const srcs = fs.readdirSync(path.join(EX, 'fpga')).map(f => ({ path: `fpga/${f}`, lang: 'vhdl', text: fs.readFileSync(path.join(EX, 'fpga', f), 'utf8') }));
  return elaborate(compile(srcs), 'uart').top.ports.map(ucfPort);
})();
// a .bit's configuration data (its header names the design, its date and time)
const bitData = file => { const b = fs.readFileSync(file); return b.subarray(b.indexOf(Buffer.from([0xaa, 0x99, 0x55, 0x66]))); };

test('#5446 a node\'s constraints from its pins: the uart example\'s UCF on the Basys2, its header the node\'s', () => {
  const c = nodeConstraints(NODE, PORTS);
  assert.equal(c.path, 'fpga.ucf');
  const body = t => t.split('\n').filter(l => !l.startsWith('#') && l.trim());
  assert.deepEqual(body(c.text), body(fs.readFileSync(path.join(ROOT, 'examples/uart/constraints/top.ucf'), 'utf8')));
  assert.equal(c.text.split('\n')[0], '# UCF for the System node \'fpga\' (top \'uart\') on Digilent Basys2 (xc3s250e-4-cp132), generated by Silinx');
  assert.ok(c.text.includes('NET "clk"    CLOCK_DEDICATED_ROUTE = FALSE ;'), 'the board\'s clock pin\'s route');
  // (the derived project: an FPGA project, its top the module, the board's device; the project's own fields kept)
  const pj = nodeProject({ name: 'p', profile: 'system', board: null, top: '', files: [{ path: 'fpga/uart.vhd' }, { path: 'uno/a.c' }, { path: 'fpga2/x.vhd' }] }, NODE, c.path);
  assert.deepEqual([pj.profile, pj.kind, pj.top, pj.board, pj.device.part, pj.constraints, pj.files.length], [undefined, undefined, 'uart', 'basys2', 'xc3s250e', 'fpga.ucf', 1]);
  assert.deepEqual(pj.files, [{ path: 'fpga/uart.vhd' }], 'its folder\'s files only (#5488)');
});

test('#5446 the refusals: no FPGA node, no module, no board, an unknown board, no pin', () => {
  assert.equal(nodeRefusal(NODE), null);
  assert.equal(nodeRefusal({ id: 'uno', kind: 'mcu' }), 'uno: only an FPGA node is implemented on a board');
  assert.equal(nodeRefusal({ ...NODE, module: null }), 'fpga: an FPGA node with no module');
  assert.equal(nodeRefusal({ ...NODE, board: null }), 'fpga: an FPGA node with no board');
  assert.equal(nodeRefusal({ ...NODE, board: 'robot' }), 'fpga: no FPGA board \'robot\' (variant 250)');
  assert.equal(nodeRefusal({ ...NODE, pins: {} }), 'fpga: its module\'s ports are on no pin of its board (the System editor\'s Pins of the board)');
  assert.equal(nodeBoard({ board: 'nexys2', variant: '1200' }).device.part, 'xc3s1200e');
});

test('#5446 the server\'s refusals: no such node, another toolchain, a project with no System as its top', async () => {
  await P.createProject({ name: 'ua', template: 'uart-avr' });
  await assert.rejects(startNodeImplementation('ua', { node: 'uno' }), { message: 'no FPGA node \'uno\' in the System of \'ua\' (fpga)' });
  await assert.rejects(startImplementation('ua', { node: 'fpga', toolchain: 'ise' }), { message: 'a System\'s FPGA node is implemented by the Silinx toolchain, for now' });
  await P.createProject({ name: 'bl', template: 'blinky' });
  await assert.rejects(startNodeImplementation('bl', { node: '*' }), { message: 'the project \'bl\' has no System as its top: implement it as an FPGA project' });
});

test('#5446 the uart-avr example\'s FPGA node implemented on its Basys2: the uart example\'s bitstream; the project untouched; Implement System', async () => {
  // (the reference: the uart example, its module on the Basys2 with these pins)
  await P.createProject({ name: 'ref', template: 'uart' });
  const ref = await waitJob(jobs, (await startImplementation('ref', { toolchain: 'silinx' })).id, { timeoutMs: 600000 });
  assert.equal(ref.status, 'ok', ref.lines.join('\n'));
  const desc = fs.readFileSync(path.join(P.projectDir('ua'), 'silinx.json'), 'utf8');
  const j = await waitJob(jobs, (await startImplementation('ua', { node: 'fpga' })).id, { timeoutMs: 600000 });
  assert.equal(j.status, 'ok', j.lines.join('\n'));
  assert.ok(j.lines.includes('System node fpga: its module uart on basys2 (250), its constraints fpga.ucf from its pins, built in build/nodes/fpga/.'), j.lines.join('\n'));
  assert.ok(j.lines.includes('System node fpga: done.'));
  assert.deepEqual(j.lines.filter(l => /^(WARNING|ERROR)/.test(l)), ref.lines.filter(l => /^(WARNING|ERROR)/.test(l)));
  const bit = path.join(P.projectDir('ua'), 'build/nodes/fpga/build/uart.bit');
  assert.ok(bitData(bit).equals(bitData(path.join(P.projectDir('ref'), 'build/uart.bit'))), 'the same configuration as the uart example\'s');
  assert.equal(fs.readFileSync(path.join(P.projectDir('ua'), 'silinx.json'), 'utf8'), desc);
  assert.deepEqual(fs.readdirSync(path.join(P.projectDir('ua'), 'build')), ['nodes']);
  // (its folder alone built, #5488: the Arduino's not copied)
  assert.deepEqual(fs.readdirSync(path.join(P.projectDir('ua'), 'build/nodes/fpga')).sort(), ['build', 'fpga', 'fpga.ucf']);
  // Implement System: every FPGA node (the one), its line; a second run while one runs refused
  const s = await startNodeImplementation('ua', { node: '*', steps: ['synth'] });
  await assert.rejects(startNodeImplementation('ua', { node: '*' }), { status: 409 });
  const sj = await waitJob(jobs, s.id, { timeoutMs: 600000 });
  assert.equal(sj.status, 'ok', sj.lines.join('\n'));
  assert.deepEqual(sj.result, { nodes: ['fpga'] });
});

const BAD_IDS = ['../x', 'a/b', '..', '/tmp/x', '../../..'];
const idError = (id) => `'${id}' is not a node's id: a letter, then letters, digits and _`;

test('#5446 a node\'s id is an identifier: refused by the reading, the check and the implementation, with their messages', () => {
  for (const id of BAD_IDS) {
    const text = JSON.stringify({ format: 'silinx-system', version: 2, name: 's', nodes: [{ ...NODE, id }], links: [] });
    assert.deepEqual(readSystem(text), { error: idError(id) }, id);
    assert.deepEqual(checkSystem({ name: 's', nodes: [{ ...NODE, id }], links: [] }).filter((d) => d.severity === 'error').map((d) => d.message), [idError(id)], id);
    assert.equal(nodeRefusal({ ...NODE, id }), idError(id), id);
  }
  assert.equal(nodeRefusal({ ...NODE, id: undefined }), idError(''));
});

test('#5446 a System whose node\'s id would leave build/nodes: Implement refuses before touching the disk; nothing outside removed or written', async () => {
  for (const [k, id] of BAD_IDS.entries()) {
    const name = `bad${k}`;
    await P.createProject({ name, template: 'uart-avr' });
    const dir = P.projectDir(name), sysFile = path.join(dir, 'uart_avr.sys.json');
    const sys = JSON.parse(fs.readFileSync(sysFile, 'utf8'));
    sys.nodes.find((n) => n.kind === 'fpga').id = id;
    fs.writeFileSync(sysFile, JSON.stringify(sys, null, 2));
    // (sentinels: in the project, in build/, beside the workspace)
    fs.mkdirSync(path.join(dir, 'build'), { recursive: true });
    const sentinels = [path.join(dir, 'keep.txt'), path.join(dir, 'build', 'keep.txt'), path.join(path.dirname(dir), `keep-${k}.txt`)];
    for (const f of sentinels) fs.writeFileSync(f, 'keep');
    for (const node of ['*', id]) await assert.rejects(startNodeImplementation(name, { node }), { status: 400, message: `uart_avr.sys.json: ${idError(id)}` }, `${id} ${node}`);
    for (const f of sentinels) assert.equal(fs.readFileSync(f, 'utf8'), 'keep', f);
    assert.deepEqual(fs.readdirSync(path.join(dir, 'build')), ['keep.txt'], `${id}: nothing written in build/`);
  }
});
